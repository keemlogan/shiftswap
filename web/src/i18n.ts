/** Korean display names of the seed people and store (spec §10); names are stored in English. */
const KO_NAMES: Record<string, string> = {
  'Park Jiyoung': '박지영',
  'Lee Seoyeon': '이서연',
  'Choi Minho': '최민호',
  'Jung Hana': '정하나',
  'Kang Doyun': '강도윤',
  'Dalbit Café': '달빛카페',
};

const MINUS = '−';

function str(v: unknown): string {
  return v == null ? '' : String(v);
}

export function createI18n(lang: Lang) {
  const dict = DICTS[lang];
  const t = (key: TextKey, params: Record<string, string | number> = {}): string =>
    dict[key].replace(/\{(\w+)\}/g, (_, k: string) => (params[k] != null ? String(params[k]) : ''));

  const name = (stored: string | null | undefined): string => {
    const s = str(stored).trim();
    return (lang === 'ko' && KO_NAMES[s]) || s;
  };
  /** '최민호님' / 'Choi Minho'. */
  const person = (stored: string | null | undefined): string => t('common.nameSuffix', { name: name(stored) });
  const initial = (stored: string): string => name(stored).slice(0, 1);

  const num = (n: number): string => Math.abs(n).toLocaleString('en-US', { maximumFractionDigits: 2 });
  /** '33,024원' / '₩33,024'; negative with a minus sign. */
  const won = (n: number): string => `${n < 0 ? MINUS : ''}${t('common.won', { n: num(n) })}`;
  /** '+51,600원' / '−52,500원' / '0원'. */
  const signedWon = (n: number): string => (n > 0 ? `+${won(n)}` : won(n));
  /** '16시간' / '16 h'. */
  const hours = (h: number): string => `${h < 0 ? MINUS : ''}${t('common.hours', { h: num(h) })}`;
  const perWeek = (h: number): string => t('common.perWeek', { h: hours(h) });

  const weekday = (date: string): string => DAYS[lang][isoWeekday(date)];
  const dayName = (wd: number): string => DAYS[lang][wd];
  const dayLong = (date: string): string => DAYS_LONG[lang][isoWeekday(date)];
  /** '9월 30일(수)' / 'Wed, Sep 30'. */
  const date = (d: string): string => {
    const [, m, day] = d.slice(0, 10).split('-').map(Number);
    return lang === 'ko' ? `${m}월 ${day}일(${weekday(d)})` : `${weekday(d)}, ${MONTHS[m - 1]} ${day}`;
  };
  /** '9/30(수)' / 'Wed 9/30'. */
  const dateShort = (d: string): string => {
    const [, m, day] = d.slice(0, 10).split('-').map(Number);
    return lang === 'ko' ? `${m}/${day}(${weekday(d)})` : `${weekday(d)} ${m}/${day}`;
  };
  /** '2026.3.2' / 'Mar 2, 2026'. */
  const ymdText = (d: string | null | undefined): string => {
    if (!d) return '';
    const [y, m, day] = d.slice(0, 10).split('-').map(Number);
    return lang === 'ko' ? `${y}.${m}.${day}` : `${MONTHS[m - 1]} ${day}, ${y}`;
  };
  const overnight = (start: string, end: string): boolean => end <= start;
  /** '18:00–23:00'; a shift ending the next day: '22:00–다음 날 02:00' / '22:00–02:00 (next day)'. */
  const range = (start: string, end: string): string => {
    if (!overnight(start, end)) return `${start}–${end}`;
    return lang === 'ko' ? `${start}–${t('common.nextDay')} ${end}` : `${start}–${end} (${t('common.nextDay')})`;
  };
  /** '9월 30일(수) 18:00–23:00' / 'Wed, Sep 30 · 18:00–23:00'. */
  const shift = (s: { work_date: string; start_time: string; end_time: string }): string =>
    (lang === 'ko' ? `${date(s.work_date)} ${range(s.start_time, s.end_time)}` : `${date(s.work_date)} · ${range(s.start_time, s.end_time)}`);
  /** Relative to now: '내일 21:00' / 'tomorrow, 21:00'; later dates in full. */
  const when = (ts: string | null | undefined, now: string | null | undefined): string => {
    if (!ts) return '';
    const d = ts.slice(0, 10);
    const time = ts.slice(11, 16);
    const diff = now ? daysBetween(now.slice(0, 10), d) : 99;
    if (lang === 'ko') {
      if (diff === 0) return `오늘 ${time}`;
      if (diff === 1) return `내일 ${time}`;
      return `${date(d)} ${time}`;
    }
    if (diff === 0) return `today, ${time}`;
    if (diff === 1) return `tomorrow, ${time}`;
    return `${date(d)}, ${time}`;
  };
  /** 'D-2' / '오늘' / '내일'. */
  const dday = (d: string, now: string | null | undefined): string => {
    if (!now) return '';
    const diff = daysBetween(now.slice(0, 10), d);
    if (diff === 0) return t('common.today');
    if (diff === 1) return t('common.tomorrow');
    return t('common.dday', { n: diff });
  };
  /** The header clock: '9/28(월) 09:00' / 'Mon 9/28 09:00'. */
  const clock = (ts: string): string => `${dateShort(ts)} ${ts.slice(11, 16)}`;
  /** '2026년 9월' / 'September 2026'. */
  const month = (ym: string): string => {
    const [y, m] = ym.split('-').map(Number);
    return lang === 'ko' ? `${y}년 ${m}월` : `${MONTHS_LONG[m - 1]} ${y}`;
  };
  /** '9월' / 'September'. */
  const monthShort = (ym: string): string => {
    const m = Number(ym.slice(5, 7));
    return lang === 'ko' ? `${m}월` : MONTHS_LONG[m - 1];
  };
  /** '최민호님, 강도윤님' / 'Choi Minho, Kang Doyun'. */
  const people = (names: string[]): string => names.map(person).join(t('common.listJoin'));

  /** '월·수 18:00–23:00, 토 12:00–18:00' / 'Mon, Wed 18:00–23:00, Sat 12:00–18:00'. */
  const fixedSummary = (fixed: FixedSlot[]): string => {
    const groups = new Map<string, string[]>();
    for (const f of fixed) {
      const r = `${f.start_time}–${f.end_time}`;
      if (!groups.has(r)) groups.set(r, []);
      groups.get(r)!.push(dayName(f.weekday));
    }
    const sep = lang === 'ko' ? '·' : ', ';
    return [...groups].map(([r, days]) => `${days.join(sep)} ${r}`).join(', ');
  };

  /** The reason a week has no holiday allowance (BR-06), as a short phrase. */
  const reasonText = (reasons: Reason[], contractHours: number): string => {
    const parts: string[] = [];
    for (const r of reasons) {
      if (r.code === 'CONTRACT_BELOW_15') parts.push(t('reason.contract', { h: hours(contractHours) }));
      if (r.code === 'ABSENT' && r.date) parts.push(t('reason.absent', { day: dateShort(r.date) }));
      if (r.code === 'GAVE_AWAY' && r.date) parts.push(t('reason.gaveAway', { day: dateShort(r.date) }));
    }
    return parts.join(t('common.sep'));
  };

  const errorText = (err: unknown): string => {
    if (!(err instanceof ApiError)) return t('err.UNKNOWN');
    const p = err.params;
    const has = (key: string) => key in dict;
    switch (err.code) {
      case 'ALREADY_TAKEN':
        return t('err.ALREADY_TAKEN', { name: name(str(p.acceptor_name)) });
      case 'REQUEST_CLOSED':
        return t(p.status === 'EXPIRED' ? 'err.REQUEST_CLOSED_EXPIRED' : 'err.REQUEST_CLOSED');
      case 'ACCEPTOR_BUSY':
        return t('err.ACCEPTOR_BUSY', { date: p.work_date ? dateShort(str(p.work_date)) : '', range: range(str(p.start_time), str(p.end_time)) });
      case 'OVERLAP':
        if ('a' in p) {
          const slot = (x: unknown) => {
            const s = (x || {}) as { weekday?: number; start_time?: string; end_time?: string };
            return `${dayName(Number(s.weekday) || 1)} ${str(s.start_time).slice(0, 5)}–${str(s.end_time).slice(0, 5)}`;
          };
          return t('err.OVERLAP_FIXED', { a: slot(p.a), b: slot(p.b) });
        }
        return t('err.OVERLAP', { name: name(str(p.name)), date: p.work_date ? dateShort(str(p.work_date)) : '', range: range(str(p.start_time), str(p.end_time)) });
      case 'OUTSIDE_CONTRACT':
        return t('err.OUTSIDE_CONTRACT', { name: name(str(p.name)), date: p.work_date ? date(str(p.work_date)) : '' });
      case 'TIME_INVALID':
        return t('slot' in p || p.field === 'slots' ? 'err.TIME_INVALID_FIXED' : 'err.TIME_INVALID');
      case 'MIN_WAGE_UNACKNOWLEDGED': {
        const workers = Array.isArray(p.workers) ? (p.workers as { name: string }[]) : [];
        return t('err.MIN_WAGE_UNACKNOWLEDGED', { names: people(workers.map((w) => w.name)) });
      }
      case 'WORKER_INVALID':
      case 'SETTINGS_INVALID': {
        const specific = `err.${err.code}_${str(p.field)}`;
        return has(specific) ? t(specific as TextKey) : t(`err.${err.code}` as TextKey);
      }
      default:
        if (has(`err.${err.code}`)) return t(`err.${err.code}` as TextKey);
        return err.hint || t('err.UNKNOWN');
    }
  };

  /** A notification's sentence, composed from its kind and params in the chosen language. */
  const notificationText = (n: NotificationItem, viewerRole: Role, now: string | null | undefined): string => {
    const p = n.params;
    if (n.kind === 'PAYROLL_DRAFT_READY') return t('notif.PAYROLL_DRAFT_READY', { month: monthShort(str(p.year_month)) });
    const owner = n.kind === 'REQUEST_FAILED' && viewerRole === 'OWNER';
    const key = `notif.${n.kind}${owner ? 'owner' : ''}` as TextKey;
    const params = {
      requester: name(p.requester_name),
      acceptor: name(p.acceptor_name),
      shift: p.work_date && p.start_time && p.end_time
        ? shift({ work_date: p.work_date, start_time: p.start_time, end_time: p.end_time }) : '',
      deadline: t('common.until', { when: when(p.deadline, now) }),
    };
    return t(key, params);
  };

  return {
    lang, t, name, person, initial, won, signedWon, hours, perWeek, weekday, dayName, dayLong, date, dateShort,
    ymd: ymdText, range, overnight, shift, when, dday, clock, month, monthShort, people, fixedSummary, reasonText,
    errorText, notificationText,
  };
}

export type I18n = ReturnType<typeof createI18n>;

export const I18nContext = createContext<{ i18n: I18n; setLang: (lang: Lang) => void } | null>(null);

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('I18nContext missing');
  return ctx.i18n;
}

export function useSetLang(): (lang: Lang) => void {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('I18nContext missing');
  return ctx.setLang;
}
