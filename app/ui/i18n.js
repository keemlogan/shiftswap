const DICTS = { en, ko };
const DAYS = { en: ['', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'], ko: ['', '월', '화', '수', '목', '금', '토', '일'] };

let lang = 'en';
try {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'ko' || saved === 'en') lang = saved;
} catch {
  // Storage blocked: stay in English.
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'ko' ? 'ko' : 'en';
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // Storage blocked: the choice lasts until reload.
  }
  document.documentElement.lang = lang;
}

/** Translate a key, filling {name} slots from params. */
export function t(key, params = {}) {
  const text = DICTS[lang][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

/** Escape text for insertion into HTML. */
export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

export function dayName(weekday) {
  return DAYS[lang][weekday];
}

/** 'Wed 09-30' / '9/30(수)'. */
export function fmtDay(date) {
  const wd = isoWeekday(date);
  const [, m, d] = date.split('-');
  return lang === 'ko' ? `${Number(m)}/${Number(d)}(${DAYS.ko[wd]})` : `${DAYS.en[wd]} ${m}-${d}`;
}

/** 'Wed 09-30 18:00' from an ISO datetime. */
export function fmtDateTime(iso) {
  if (!iso) return '';
  return `${fmtDay(iso.slice(0, 10))} ${iso.slice(11, 16)}`;
}

export function fmtShift(s) {
  return `${fmtDay(s.workDate)} ${s.startTime}–${s.endTime}`;
}

export function fmtHours(h) {
  return t('common.hours', { h: Number(h).toLocaleString('en-US', { maximumFractionDigits: 2 }) });
}

export function fmtWon(n) {
  return t('common.won', { n: Number(n).toLocaleString('en-US') });
}

/** Wrap a number-like text in the monospace tabular style. */
export function num(text) {
  return `<span class="num">${esc(text)}</span>`;
}

/** Text of a failed service call. */
export function errorText(err) {
  if (err && err.code && (en[`err.${err.code}`])) {
    const params = { ...err.params };
    if (params.day) params.dayName = dayName(params.day);
    if (err.code === 'DEADLINE_AFTER_START' && params.start) params.start = fmtDateTime(params.start.replace(' ', 'T'));
    return t(`err.${err.code}`, params);
  }
  return (err && err.message) || String(err);
}

/** Text of a notification, rebuilt from its request so it follows the language switch. */
export function notificationText(n) {
  if (!n.workDate) return n.message;
  return t(`notif.${n.kind}`, {
    requester: n.requesterName,
    acceptor: n.acceptorName || '',
    shift: fmtShift(n),
    deadline: fmtDateTime(n.deadline),
  });
}

/** Show a failed save inside its form, keeping what the user typed. */
export function showFormError(form, err) {
  if (!err || !err.code) console.error(err);
  let box = form.querySelector('.form-error');
  if (!box) {
    box = document.createElement('p');
    box.className = 'notice notice-alert form-error';
    box.setAttribute('role', 'alert');
    const heading = form.querySelector('h2, h3');
    if (heading) heading.after(box);
    else form.prepend(box);
  }
  box.textContent = errorText(err);
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** 'September 2026' / '2026년 9월' from 'YYYY-MM'. */
export function fmtMonth(yearMonth) {
  const [y, m] = yearMonth.split('-').map(Number);
  return lang === 'ko' ? `${y}년 ${m}월` : `${MONTHS[m - 1]} ${y}`;
}

/** Page header: title, one sentence on what the page is for, optional actions. */
export function pageHead(title, purpose, actions = '') {
  return `
    <header class="page-head">
      <div class="page-title">
        <h1>${esc(title)}</h1>
        <p class="purpose">${esc(purpose)}</p>
      </div>
      ${actions ? `<div class="actions">${actions}</div>` : ''}
    </header>`;
}

/** Empty state: what will appear here, and the next action as a button or link. */
export function emptyState(text, action = '') {
  return `<div class="empty-state"><p>${esc(text)}</p>${action}</div>`;
}
