const DICTS = { ko, en };
const DAYS = { en: ['', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'], ko: ['', '월', '화', '수', '목', '금', '토', '일'] };
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const MONTHS_LONG = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

let lang = 'ko';
try {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'ko' || saved === 'en') lang = saved;
} catch {
  // Storage blocked: stay in Korean.
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'ko';
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // Storage blocked: the choice lasts until reload.
  }
  document.documentElement.lang = lang;
}

/** Translate a key, filling {name} slots from params. */
export function t(key, params = {}) {
  const text = DICTS[lang][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

/** Escape text for insertion into HTML. */
export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

export function dayName(weekday) {
  return DAYS[lang][weekday];
}

/** '수요일' / 'Wednesday'. */
export function dayLong(date) {
  return t('weekday.long').split(',')[isoWeekday(date)];
}

/** Korean display names for the seed people and store (spec §10). Stored names stay English. */
const KO_NAMES = {
  'Park Jiyoung': '박지영',
  'Lee Seoyeon': '이서연',
  'Choi Minho': '최민호',
  'Jung Hana': '정하나',
  'Kang Doyun': '강도윤',
  'Dalbit Café': '달빛카페',
};

/** A person or store name as shown: '최민호' in Korean for the seed data; names not in the map as stored. */
export function displayName(name) {
  const stored = String(name || '').trim();
  return (lang === 'ko' && KO_NAMES[stored]) || stored;
}

/**
 * Name for sentences: in English the given name ('Choi Minho' → 'Minho'; names are stored family name first), in
 * Korean the full display name ('최민호'). Korean templates add the honorific 님 themselves.
 */
export function given(name) {
  if (lang === 'ko') return displayName(name);
  const parts = String(name || '').trim().split(/\s+/);
  return parts.length > 1 ? parts.slice(1).join(' ') : parts[0];
}

/** '최민호님' / 'Minho'. */
export function honorific(name) {
  return t('common.nameSuffix', { name: given(name) });
}

/** One letter for an avatar: '최' / 'M'. */
export function initial(name) {
  return given(name).slice(0, 1);
}

/** '9월 30일(수)' / 'Wed, Sep 30'. */
export function fmtDate(date) {
  const [, m, d] = date.split('-').map(Number);
  const wd = isoWeekday(date);
  return lang === 'ko' ? `${m}월 ${d}일(${DAYS.ko[wd]})` : `${DAYS.en[wd]}, ${MONTHS[m - 1]} ${d}`;
}

/** '9/30(수)' / 'Wed 9/30' — compact, for column heads and history lines. */
export function fmtDateShort(date) {
  const [, m, d] = date.split('-').map(Number);
  const wd = isoWeekday(date);
  return lang === 'ko' ? `${m}/${d}(${DAYS.ko[wd]})` : `${DAYS.en[wd]} ${m}/${d}`;
}

/** '9월 30일(수) 18:00–23:00' / 'Wed, Sep 30 · 18:00–23:00'. */
export function fmtShift(s) {
  return lang === 'ko' ? `${fmtDate(s.workDate)} ${s.startTime}–${s.endTime}` : `${fmtDate(s.workDate)} · ${s.startTime}–${s.endTime}`;
}

/** Relative datetime from `nowIso`: '내일 21:00' / 'tomorrow, 21:00'; later dates in full. */
export function fmtWhen(iso, nowIso) {
  if (!iso) return '';
  const date = iso.slice(0, 10);
  const time = iso.slice(11, 16);
  const diff = daysBetween(nowIso.slice(0, 10), date);
  if (lang === 'ko') {
    if (diff === 0) return `오늘 ${time}`;
    if (diff === 1) return `내일 ${time}`;
    return `${fmtDate(date)} ${time}`;
  }
  if (diff === 0) return `today, ${time}`;
  if (diff === 1) return `tomorrow, ${time}`;
  return `${fmtDate(date)}, ${time}`;
}

/** 'D-2' / '오늘' / '내일'. */
export function dday(date, nowIso) {
  const diff = daysBetween(nowIso.slice(0, 10), date);
  if (diff === 0) return t('common.today');
  if (diff === 1) return t('common.tomorrow');
  return t('common.dday', { n: diff });
}

/** The demo clock chip: '9/28(월) 09:00' / 'Mon 9/28 09:00'. */
export function fmtClock(iso) {
  return `${fmtDateShort(iso.slice(0, 10))} ${iso.slice(11, 16)}`;
}

/** '2026.3.2' / 'Mar 2, 2026' — a calendar date without the weekday. */
export function fmtYMD(date) {
  if (!date) return '';
  const [y, m, d] = date.split('-').map(Number);
  return lang === 'ko' ? `${y}.${m}.${d}` : `${MONTHS[m - 1]} ${d}, ${y}`;
}

/** '2026년 9월' / 'September 2026'. */
export function fmtMonth(yearMonth) {
  const [y, m] = yearMonth.split('-').map(Number);
  return lang === 'ko' ? `${y}년 ${m}월` : `${MONTHS_LONG[m - 1]} ${y}`;
}

/** '9월' / 'September' — for button labels. */
export function fmtMonthShort(yearMonth) {
  const m = Number(yearMonth.slice(5, 7));
  return lang === 'ko' ? `${m}월` : MONTHS_LONG[m - 1];
}

export function fmtHours(h) {
  return t('common.hours', { h: Number(h).toLocaleString('en-US', { maximumFractionDigits: 2 }) });
}

export function fmtWon(n) {
  return t('common.won', { n: Number(n).toLocaleString('en-US') });
}

/** A number-like text in tabular figures. */
export function num(text) {
  return `<span class="num">${esc(text)}</span>`;
}

/** Join names as '최민호님, 강도윤님' / 'Minho, Doyun'. */
export function joinPeople(names) {
  return names.map(honorific).join(t('common.listJoin'));
}

/** Text of a failed service call. */
export function errorText(err) {
  if (err && err.code && en[`err.${err.code}`]) {
    const params = { ...err.params };
    if (params.day) params.dayName = dayName(params.day);
    if (params.name) params.name = given(params.name);
    if (err.code === 'DEADLINE_AFTER_START' && params.start) {
      const [date, time] = params.start.split(' ');
      params.start = `${fmtDate(date)} ${time}`;
    }
    return t(`err.${err.code}`, params);
  }
  return (err && err.message) || String(err);
}

/** Text of a notification, rebuilt from its request so it follows the language switch. */
export function notificationText(n, nowIso, viewer = null) {
  if (n.kind === 'PAYROLL_DRAFT_READY') return t('notif.PAYROLL_DRAFT_READY', { month: fmtMonthShort(n.yearMonth) });
  if (!n.workDate) return n.message;
  const owner = n.kind === 'REQUEST_FAILED' && viewer && viewer.role === 'OWNER';
  return t(`notif.${n.kind}${owner ? 'owner' : ''}`, {
    requester: given(n.requesterName),
    acceptor: n.acceptorName ? given(n.acceptorName) : '',
    shift: fmtShift(n),
    deadline: t('common.until', { when: fmtWhen(n.deadline, nowIso) }),
  });
}

/** Show a failed save inside its form, keeping what the user typed. */
export function showFormError(form, err) {
  if (!err || !err.code) console.error(err);
  let box = form.querySelector('.form-error');
  if (!box) {
    box = document.createElement('p');
    box.className = 'notice notice-alert form-error';
    box.setAttribute('role', 'alert');
    form.prepend(box);
  }
  box.textContent = errorText(err);
  box.scrollIntoView({ block: 'nearest' });
}

