-- §9.4, A3: "now" — the demo clock while it is set, otherwise the database server time in Korea.
create or replace function public.app_now() returns timestamp
language sql stable security definer set search_path = '' as $$
  select coalesce((select wp.demo_clock from public.workplace wp order by wp.id limit 1),
                  now() at time zone 'Asia/Seoul')
$$;

create or replace function public.ss_owner_id() returns int
language sql stable security definer set search_path = '' as $$
  select w.id from public.worker w where w.role = 'OWNER' order by w.id limit 1
$$;

-- BR-06: weekly contractual hours C, in minutes = the sum of the worker's fixed slots.
create or replace function public.ss_contract_minutes(p_worker_id int) returns int
language sql stable security definer set search_path = '' as $$
  select coalesce(sum(public.ss_minutes(f.start_time, f.end_time)), 0)::int
  from public.fixed_schedule f where f.worker_id = p_worker_id
$$;

-- FR-14: a week is read-only once the payroll of the month of its Sunday (the month that pays its holiday allowance,
-- BR-11) is confirmed.
create or replace function public.ss_week_frozen(p_week_start date) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.payroll p
                 where p.year_month = to_char((public.ss_week_start(p_week_start) + 6)::timestamp, 'YYYY-MM')
                   and p.status = 'CONFIRMED')
$$;

-- BR-09: the minimum hourly wage of a year (the latest row not after that year).
create or replace function public.ss_minimum_wage(p_year int) returns int
language sql stable security definer set search_path = '' as $$
  select m.hourly from public.minimum_wage m where m.year <= p_year order by m.year desc limit 1
$$;

-- BR-10: the probation reduction applies on p_date. A contract of at least one year: the last contract day is on or
-- after the day before the first anniversary (2026-09-01 to 2027-08-31 is one year), or the contract is open-ended.
create or replace function public.ss_probation(p_worker_id int, p_date date) returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((
    select w.probation_end is not null and w.contract_start is not null and not w.simple_labor
       and (w.contract_end is null or w.contract_end + 1 >= (w.contract_start + interval '1 year')::date)
       and p_date >= w.contract_start
       and p_date < (w.contract_start + interval '3 months')::date
       and p_date <= w.probation_end
    from public.worker w where w.id = p_worker_id), false)
$$;

-- BR-01 / BR-05 / FR-05: a shift of the worker whose interval overlaps [p_date + p_start, end) on the time line
-- (shifts last at most 16 h, so only the day before and the day after can reach the date), or null.
create or replace function public.ss_overlapping_shift(p_worker_id int, p_date date, p_start time, p_end time,
                                                       p_except int) returns int
language sql stable security definer set search_path = '' as $$
  select s.id from public.shift s
  where s.worker_id = p_worker_id and s.id is distinct from p_except
    and s.work_date between p_date - 1 and p_date + 1
    and public.ss_range(s.work_date, s.start_time, s.end_time) && public.ss_range(p_date, p_start, p_end)
  order by s.work_date, s.start_time, s.id
  limit 1
$$;

-- One shift with names, as the screens show it.
create or replace function public.ss_shift_json(p_shift_id int) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'id', s.id, 'work_date', s.work_date, 'weekday', extract(isodow from s.work_date)::int,
    'start_time', public.ss_hm(s.start_time), 'end_time', public.ss_hm(s.end_time),
    'start_at', s.work_date + s.start_time, 'end_at', public.ss_end_ts(s.work_date, s.start_time, s.end_time),
    'minutes', public.ss_minutes(s.start_time, s.end_time),
    'hours', round(public.ss_minutes(s.start_time, s.end_time) / 60.0, 2),
    'worker_id', s.worker_id, 'worker_name', w.name,
    'original_worker_id', s.original_worker_id, 'original_worker_name', o.name,
    'status', s.status, 'fixed_schedule_id', s.fixed_schedule_id)
  from public.shift s
  join public.worker w on w.id = s.worker_id
  left join public.worker o on o.id = s.original_worker_id
  where s.id = p_shift_id
$$;

-- The parameters of a request notification: names, shift date and times, deadline.
create or replace function public.ss_request_params(p_request_id int) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'request_id', r.id, 'status', r.status,
    'requester_id', r.requester_id, 'requester_name', rq.name,
    'acceptor_id', r.acceptor_id, 'acceptor_name', ac.name,
    'shift_id', s.id, 'work_date', s.work_date,
    'start_time', public.ss_hm(s.start_time), 'end_time', public.ss_hm(s.end_time),
    'deadline', r.deadline, 'reason', r.reason)
  from public.sub_request r
  join public.shift s on s.id = r.shift_id
  join public.worker rq on rq.id = r.requester_id
  left join public.worker ac on ac.id = r.acceptor_id
  where r.id = p_request_id
$$;

-- The candidates of a request and their answers.
create or replace function public.ss_targets_json(p_request_id int) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('worker_id', t.worker_id, 'name', w.name, 'response', t.response,
                                               'responded_at', t.responded_at) order by t.worker_id), '[]'::jsonb)
  from public.sub_request_target t join public.worker w on w.id = t.worker_id
  where t.sub_request_id = p_request_id
$$;

-- BR-01: the eligible candidates of a shift, [{id, name}] by id: active WORKERs other than the requester (and the
-- shift's worker) whose contract period contains the shift date and who have no shift overlapping it on the time line.
create or replace function public.ss_candidates(p_shift_id int, p_requester_id int) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', w.id, 'name', w.name) order by w.id), '[]'::jsonb)
  from public.shift s
  join public.worker w on w.role = 'WORKER' and w.active and w.id <> p_requester_id and w.id <> s.worker_id
  where s.id = p_shift_id
    and (w.contract_start is null or s.work_date >= w.contract_start)
    and (w.contract_end is null or s.work_date <= w.contract_end)
    and public.ss_overlapping_shift(w.id, s.work_date, s.start_time, s.end_time, s.id) is null
$$;

-- BR-06, BR-07, BR-08, BR-16: one worker's ISO week, optionally with shift p_move_shift handed to worker p_move_to
-- (the swap of an approval preview; the moved shift keeps its first worker as original worker).
--   contract C; scheduled minutes = the shifts the worker holds; actual minutes = the recorded minutes of WORKED
--   shifts; perfect attendance (BR-06 b): no shift the worker holds and originally had is ABSENT, and under policy
--   ABSENT no shift was given away by an approved swap (an unmarked past shift counts as worked); holiday hours and
--   pay (BR-07); week pay estimate (BR-16): base = paid scheduled minutes × wage / 60, premium = BR-08 on the week,
--   holiday as above (ABSENT shifts are not paid).
create or replace function public.ss_week_calc(p_worker_id int, p_week_start date, p_move_shift int default null,
                                               p_move_to int default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_week date := public.ss_week_start(p_week_start);
  v_wage int;
  v_policy text;
  v_employees int;
  v_contract int := public.ss_contract_minutes(p_worker_id);
  v_contract_hours numeric := round(public.ss_contract_minutes(p_worker_id) / 60.0, 2);
  v_scheduled int := 0;
  v_actual int := 0;
  v_paid int := 0;
  v_perfect boolean := true;
  v_worked_day boolean := false;
  v_reasons jsonb := '[]'::jsonb;
  v_intervals jsonb := '[]'::jsonb;
  v_eligible boolean;
  v_holiday_hours numeric;
  v_holiday_pay int;
  v_base_pay int;
  v_premium jsonb;
  v_premium_pay int;
  v_minutes int;
  v_row record;
begin
  select coalesce(w.hourly_wage, 0) into v_wage from public.worker w where w.id = p_worker_id;
  select wp.sub_attendance_policy, wp.regular_employees into v_policy, v_employees
  from public.workplace wp order by wp.id limit 1;
  if v_contract_hours < 15 then
    v_reasons := v_reasons || jsonb_build_array(jsonb_build_object('code', 'CONTRACT_BELOW_15'));
  end if;
  for v_row in
    select s.id, s.work_date, s.start_time, s.end_time, s.status, a.clock_in, a.clock_out,
           case when s.id = p_move_shift then p_move_to else s.worker_id end as holder,
           case when s.id = p_move_shift then coalesce(s.original_worker_id, s.worker_id)
                else s.original_worker_id end as original
    from public.shift s left join public.attendance a on a.shift_id = s.id
    where s.work_date between v_week and v_week + 6
    order by s.work_date, s.start_time, s.id
  loop
    if v_row.holder = p_worker_id then
      v_minutes := public.ss_minutes(v_row.start_time, v_row.end_time);
      v_scheduled := v_scheduled + v_minutes;
      if v_row.status = 'WORKED' and v_row.clock_in is not null then
        v_actual := v_actual + public.ss_range_minutes(public.ss_attendance_range(
          v_row.work_date, v_row.start_time, v_row.end_time, v_row.clock_in, v_row.clock_out));
      end if;
      if v_row.status <> 'ABSENT' then
        v_worked_day := true;
        v_paid := v_paid + v_minutes;
        v_intervals := v_intervals || jsonb_build_array(jsonb_build_object(
          'work_date', v_row.work_date, 'start', v_row.work_date + v_row.start_time,
          'end', public.ss_end_ts(v_row.work_date, v_row.start_time, v_row.end_time)));
      elsif coalesce(v_row.original, v_row.holder) = p_worker_id then
        v_perfect := false;
        v_reasons := v_reasons || jsonb_build_array(jsonb_build_object('code', 'ABSENT', 'date', v_row.work_date));
      end if;
    elsif v_row.original = p_worker_id and v_policy = 'ABSENT' then
      v_perfect := false;
      v_reasons := v_reasons || jsonb_build_array(jsonb_build_object('code', 'GAVE_AWAY', 'date', v_row.work_date));
    end if;
  end loop;
  -- BR-06 (c): a week in which W works on no day (every shift handed over, or none held) has no holiday allowance.
  if not v_worked_day and v_perfect then
    v_reasons := v_reasons || jsonb_build_array(jsonb_build_object('code', 'NO_DAY_WORKED'));
  end if;
  v_eligible := v_contract_hours >= 15 and v_perfect and v_worked_day;
  v_holiday_hours := case when v_eligible then public.ss_holiday_hours(v_contract_hours) else 0.00 end;
  v_holiday_pay := floor(v_holiday_hours * v_wage);
  v_base_pay := floor(v_paid::numeric * v_wage / 60);
  v_premium := public.ss_premium(v_intervals, v_contract, v_employees, v_week, v_week + 6);
  v_premium_pay := floor((v_premium->>'total_minutes')::numeric * v_wage / 120);
  return jsonb_build_object(
    'worker_id', p_worker_id, 'week_start', v_week,
    'contract_minutes', v_contract, 'contract_hours', v_contract_hours,
    'part_time', v_contract > 0 and v_contract < 2400,
    'scheduled_minutes', v_scheduled, 'scheduled_hours', round(v_scheduled / 60.0, 2),
    'actual_minutes', v_actual, 'actual_hours', round(v_actual / 60.0, 2),
    'perfect_attendance', v_perfect, 'holiday_eligible', v_eligible,
    'holiday_hours', v_holiday_hours, 'holiday_pay', v_holiday_pay,
    'paid_minutes', v_paid, 'base_pay', v_base_pay,
    'premium', v_premium, 'premium_hours', round((v_premium->>'total_minutes')::int / 60.0, 2),
    'premium_pay', v_premium_pay,
    'total_pay', v_base_pay + v_premium_pay + v_holiday_pay,
    'reasons', v_reasons);
end $$;

-- FR-11 / BR-16: one person of a swap, before → after, with the change of each pay component.
create or replace function public.ss_person_effect(p_before jsonb, p_after jsonb) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'worker_id', w.id, 'name', w.name, 'hourly_wage', w.hourly_wage,
    'contract_hours', p_before->'contract_hours', 'part_time', p_before->'part_time',
    'before', p_before, 'after', p_after,
    'change', jsonb_build_object(
      'scheduled_hours', round(((p_after->>'scheduled_minutes')::int - (p_before->>'scheduled_minutes')::int) / 60.0, 2),
      'base_pay', (p_after->>'base_pay')::int - (p_before->>'base_pay')::int,
      'premium_pay', (p_after->>'premium_pay')::int - (p_before->>'premium_pay')::int,
      'holiday_pay', (p_after->>'holiday_pay')::int - (p_before->>'holiday_pay')::int,
      'total', (p_after->>'total_pay')::int - (p_before->>'total_pay')::int),
    'eligibility_changed', (p_before->>'holiday_eligible')::boolean <> (p_after->>'holiday_eligible')::boolean)
  from public.worker w where w.id = (p_before->>'worker_id')::int
$$;

-- FR-11, FR-24, BR-15, BR-16: the effect of handing shift p_shift_id from its current worker to p_acceptor_id on the
-- ISO week of the shift, for both people, the store's labour cost change and the part-time limit warning.
create or replace function public.ss_swap_effect(p_shift_id int, p_acceptor_id int) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_shift public.shift;
  v_week date;
  v_policy text;
  v_employees int;
  v_requester jsonb;
  v_acceptor jsonb;
  v_after jsonb;
  v_beyond int;
  v_warning jsonb := null;
begin
  select * into v_shift from public.shift where id = p_shift_id;
  v_week := public.ss_week_start(v_shift.work_date);
  select wp.sub_attendance_policy, wp.regular_employees into v_policy, v_employees
  from public.workplace wp order by wp.id limit 1;
  v_requester := public.ss_person_effect(public.ss_week_calc(v_shift.worker_id, v_week),
                                         public.ss_week_calc(v_shift.worker_id, v_week, v_shift.id, p_acceptor_id));
  v_after := public.ss_week_calc(p_acceptor_id, v_week, v_shift.id, p_acceptor_id);
  v_acceptor := public.ss_person_effect(public.ss_week_calc(p_acceptor_id, v_week), v_after);
  -- BR-15: S − C of a part-time acceptor beyond 12 h, only with five or more regular employees.
  v_beyond := (v_after->>'scheduled_minutes')::int - (v_after->>'contract_minutes')::int;
  if v_employees >= 5 and (v_after->>'part_time')::boolean and v_beyond > 720 then
    v_warning := jsonb_build_object('beyond_contract', round(v_beyond / 60.0, 2), 'limit', 12);
  end if;
  return jsonb_build_object(
    'shift', public.ss_shift_json(v_shift.id),
    'week_start', v_week,
    'policy', v_policy,
    'regular_employees', v_employees,
    'requester', v_requester,
    'acceptor', v_acceptor,
    'store_total_change', (v_requester->'change'->>'total')::int + (v_acceptor->'change'->>'total')::int,
    'warning', v_warning);
end $$;


