-- FR-12, BR-12, BR-04: expiry first; then APPROVE (shift to the acceptor, original worker kept, both weeks
-- recomputed, REQUEST_APPROVED to both) or REJECT (shift unchanged, REQUEST_REJECTED to both). Only an ACCEPTED
-- request before its deadline and shift start can be decided. Returns {id, status}.
create or replace function public.decide_sub_request(p_request_id int, p_decision text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_request public.sub_request;
  v_shift public.shift;
  v_busy public.shift;
  v_status text;
  v_params jsonb;
begin
  if p_decision is null or p_decision not in ('APPROVE', 'REJECT') then
    raise exception using message = 'DECISION_INVALID', detail = jsonb_build_object('decision', p_decision)::text,
      hint = 'Decide with APPROVE or REJECT.';
  end if;
  if not exists (select 1 from public.sub_request r where r.id = p_request_id) then
    raise exception using message = 'REQUEST_NOT_FOUND', detail = jsonb_build_object('request_id', p_request_id)::text,
      hint = 'This request does not exist. Reload the page.';
  end if;
  perform public.expire_overdue_requests();
  select * into v_request from public.sub_request where id = p_request_id;
  if v_request.status = 'EXPIRED' then
    raise exception using message = 'REQUEST_CLOSED',
      detail = jsonb_build_object('request_id', v_request.id, 'status', 'EXPIRED')::text,
      hint = 'This request expired at its deadline or when the shift started, so it can no longer be decided.';
  end if;
  if v_request.status <> 'ACCEPTED' then
    raise exception using message = 'NOT_ACCEPTED',
      detail = jsonb_build_object('request_id', v_request.id, 'status', v_request.status)::text,
      hint = format('Only an accepted request can be approved or rejected; this one is %s.', lower(v_request.status));
  end if;
  select * into v_shift from public.shift where id = v_request.shift_id;
  if p_decision = 'APPROVE' then
    -- BR-02: the acceptor's overlap is checked again at approval.
    select * into v_busy from public.shift
    where id = public.ss_overlapping_shift(v_request.acceptor_id, v_shift.work_date, v_shift.start_time,
                                           v_shift.end_time, v_shift.id);
    if found then
      raise exception using message = 'ACCEPTOR_BUSY',
        detail = jsonb_build_object('request_id', v_request.id, 'worker_id', v_request.acceptor_id,
                                    'shift_id', v_busy.id, 'work_date', v_busy.work_date,
                                    'start_time', public.ss_hm(v_busy.start_time),
                                    'end_time', public.ss_hm(v_busy.end_time))::text,
        hint = 'The acceptor now has another shift that overlaps this one. Reject the swap or move that shift.';
    end if;
  end if;
  v_status := case p_decision when 'APPROVE' then 'APPROVED' else 'REJECTED' end;
  update public.sub_request q set status = v_status, decided_at = v_now
  where q.id = v_request.id and q.status = 'ACCEPTED' and q.deadline > v_now
    and exists (select 1 from public.shift s where s.id = q.shift_id and s.work_date + s.start_time > v_now);
  if not found then
    select * into v_request from public.sub_request where id = p_request_id;
    raise exception using message = 'REQUEST_CLOSED',
      detail = jsonb_build_object('request_id', v_request.id, 'status', v_request.status)::text,
      hint = 'This request changed in the meantime and can no longer be decided. Reload the page.';
  end if;
  if p_decision = 'APPROVE' then
    update public.shift set worker_id = v_request.acceptor_id,
      original_worker_id = coalesce(original_worker_id, worker_id)
    where id = v_shift.id;
    perform public.ss_recompute_week(v_shift.work_date,
      array_remove(array[v_request.requester_id, v_request.acceptor_id, v_shift.original_worker_id], null));
  end if;
  v_params := public.ss_request_params(v_request.id);
  perform public.ss_notify(v_request.requester_id, v_request.id, 'REQUEST_' || v_status, v_params);
  perform public.ss_notify(v_request.acceptor_id, v_request.id, 'REQUEST_' || v_status, v_params);
  return jsonb_build_object('id', v_request.id, 'status', v_status);
end $$;

-- ---- UC-12 Cancel own substitute request ----------------------------------------------------------------------------

-- FR-19: the requester cancels a REQUESTED or ACCEPTED request; pending targets are closed and every target that was
-- PENDING or ACCEPTED receives REQUEST_CANCELLED. Returns {id, status}.
create or replace function public.cancel_sub_request(p_request_id int, p_requester_id int) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_request public.sub_request;
  v_targets int[];
  v_worker int;
  v_params jsonb;
begin
  select * into v_request from public.sub_request where id = p_request_id;
  if not found then
    raise exception using message = 'REQUEST_NOT_FOUND', detail = jsonb_build_object('request_id', p_request_id)::text,
      hint = 'This request does not exist. Reload the page.';
  end if;
  if v_request.requester_id is distinct from p_requester_id then
    raise exception using message = 'NOT_REQUESTER',
      detail = jsonb_build_object('request_id', v_request.id, 'worker_id', p_requester_id)::text,
      hint = 'Only the worker who asked for the substitute can cancel the request.';
  end if;
  perform public.expire_overdue_requests();
  update public.sub_request set status = 'CANCELLED', decided_at = v_now
  where id = v_request.id and status in ('REQUESTED', 'ACCEPTED');
  if not found then
    select * into v_request from public.sub_request where id = p_request_id;
    raise exception using message = 'REQUEST_CLOSED',
      detail = jsonb_build_object('request_id', v_request.id, 'status', v_request.status)::text,
      hint = format('This request is %s, so it can no longer be cancelled.', lower(v_request.status));
  end if;
  select coalesce(array_agg(t.worker_id order by t.worker_id), '{}') into v_targets
  from public.sub_request_target t
  where t.sub_request_id = v_request.id and t.response in ('PENDING', 'ACCEPTED');
  update public.sub_request_target set response = 'CLOSED', responded_at = v_now
  where sub_request_id = v_request.id and response = 'PENDING';
  v_params := public.ss_request_params(v_request.id);
  foreach v_worker in array v_targets loop
    perform public.ss_notify(v_worker, v_request.id, 'REQUEST_CANCELLED', v_params);
  end loop;
  return jsonb_build_object('id', v_request.id, 'status', 'CANCELLED');
end $$;

-- ---- UC-07 Record and confirm attendance ----------------------------------------------------------------------------

-- FR-13, BR-17: after the shift's scheduled end its worker records clock-in and clock-out; the interval placed on the
-- shift's time line must lie within [start − 2 h, end + 4 h] and last 30 minutes to 16 hours. Recording again replaces
-- an unconfirmed record. Returns {shift_id, clock_in, clock_out, start_at, end_at, minutes, hours}.
create or replace function public.record_attendance(p_shift_id int, p_worker_id int, p_clock_in time,
                                                    p_clock_out time) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_shift public.shift;
  v_start timestamp;
  v_end timestamp;
  v_range tsrange;
  v_minutes int;
begin
  select * into v_shift from public.shift where id = p_shift_id for update;
  if not found then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
  if v_shift.worker_id is distinct from p_worker_id then
    raise exception using message = 'NOT_YOUR_SHIFT',
      detail = jsonb_build_object('shift_id', v_shift.id, 'worker_id', p_worker_id)::text,
      hint = 'You can only record attendance for your own shift.';
  end if;
  if v_shift.status <> 'SCHEDULED' then
    raise exception using message = 'ATTENDANCE_CLOSED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'status', v_shift.status)::text,
      hint = 'The owner has already closed this shift, so the record cannot be changed.';
  end if;
  v_start := v_shift.work_date + v_shift.start_time;
  v_end := public.ss_end_ts(v_shift.work_date, v_shift.start_time, v_shift.end_time);
  if v_now < v_end then
    raise exception using message = 'SHIFT_NOT_ENDED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'end_at', v_end)::text,
      hint = 'Attendance can be recorded after the shift has ended.';
  end if;
  if not public.ss_valid_time(p_clock_in) or not public.ss_valid_time(p_clock_out) then
    raise exception using message = 'TIME_INVALID',
      detail = jsonb_build_object('clock_in', p_clock_in, 'clock_out', p_clock_out)::text,
      hint = 'Enter clock-in and clock-out as HH:MM.';
  end if;
  v_range := public.ss_attendance_range(v_shift.work_date, v_shift.start_time, v_shift.end_time,
                                        p_clock_in, p_clock_out);
  v_minutes := public.ss_range_minutes(v_range);
  if lower(v_range) < v_start - interval '2 hours' or upper(v_range) > v_end + interval '4 hours'
     or v_minutes not between 30 and 960 then
    raise exception using message = 'ATTENDANCE_IMPLAUSIBLE',
      detail = jsonb_build_object('shift_id', v_shift.id, 'clock_in', public.ss_hm(p_clock_in),
                                  'clock_out', public.ss_hm(p_clock_out), 'start_at', v_start, 'end_at', v_end,
                                  'recorded_start', lower(v_range), 'recorded_end', upper(v_range),
                                  'minutes', v_minutes)::text,
      hint = 'The recorded times must lie between 2 hours before the start and 4 hours after the end of the shift and last 30 minutes to 16 hours.';
  end if;
  insert into public.attendance (shift_id, clock_in, clock_out, confirmed)
  values (v_shift.id, p_clock_in, p_clock_out, false)
  on conflict (shift_id) do update set clock_in = excluded.clock_in, clock_out = excluded.clock_out,
                                       confirmed = false;
  return jsonb_build_object('shift_id', v_shift.id, 'clock_in', public.ss_hm(p_clock_in),
                            'clock_out', public.ss_hm(p_clock_out), 'start_at', lower(v_range),
                            'end_at', upper(v_range), 'minutes', v_minutes, 'hours', round(v_minutes / 60.0, 2));
end $$;

-- FR-13: the owner confirms a recorded attendance; the shift becomes WORKED and its week is recomputed.
create or replace function public.confirm_attendance(p_shift_id int) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_shift public.shift;
begin
  select * into v_shift from public.shift where id = p_shift_id for update;
  if not found then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
  if v_shift.status <> 'SCHEDULED' then
    raise exception using message = 'ATTENDANCE_CLOSED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'status', v_shift.status)::text,
      hint = format('This shift is already %s, so its status cannot change again.', lower(v_shift.status));
  end if;
  if not exists (select 1 from public.attendance a where a.shift_id = v_shift.id) then
    raise exception using message = 'NO_ATTENDANCE', detail = jsonb_build_object('shift_id', v_shift.id)::text,
      hint = 'The worker has not recorded this shift yet. Ask them to record it, or mark the shift absent.';
  end if;
  update public.attendance set confirmed = true where shift_id = v_shift.id;
  update public.shift set status = 'WORKED' where id = v_shift.id and status = 'SCHEDULED';
  perform public.ss_recompute_week(v_shift.work_date,
    array_remove(array[v_shift.worker_id, v_shift.original_worker_id], null));
end $$;

-- ---- UC-08 Compute weekly hours and holiday allowance ---------------------------------------------------------------

-- FR-14: recompute and return the week's summary per worker with the reasons; a week of a confirmed month is
-- returned as stored (its reasons are explained from the current shifts).
create or replace function public.week_summary(p_week_start date) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_week date;
  v_frozen boolean;
begin
  if p_week_start is null then
    raise exception using message = 'TIME_INVALID', detail = jsonb_build_object('field', 'week_start')::text,
      hint = 'Choose the week to show.';
  end if;
  v_week := public.ss_week_start(p_week_start);
  v_frozen := public.ss_week_frozen(v_week);
  if not v_frozen then
    perform public.ss_recompute_week(v_week);
  end if;
  return jsonb_build_object(
    'week_start', v_week, 'week_end', v_week + 6, 'frozen', v_frozen,
    'policy', (select wp.sub_attendance_policy from public.workplace wp order by wp.id limit 1),
    'regular_employees', (select wp.regular_employees from public.workplace wp order by wp.id limit 1),
    'rows', coalesce((
      select jsonb_agg(jsonb_build_object(
               'worker_id', ws.worker_id, 'name', w.name, 'hourly_wage', w.hourly_wage,
               'contract_hours', ws.contract_hours, 'scheduled_hours', ws.scheduled_hours,
               'actual_hours', ws.actual_hours, 'perfect_attendance', ws.perfect_attendance,
               'holiday_eligible', ws.holiday_eligible, 'holiday_hours', ws.holiday_hours,
               'holiday_pay', ws.holiday_pay,
               'reasons', public.ss_week_calc(ws.worker_id, v_week)->'reasons') order by ws.worker_id)
      from public.weekly_summary ws join public.worker w on w.id = ws.worker_id
      where ws.week_start = v_week), '[]'::jsonb));
end $$;

-- ---- UC-09 Generate and confirm monthly payroll ---------------------------------------------------------------------

-- FR-15, FR-16, BR-08–BR-11: (re)generate the month's DRAFT rows; a confirmed month is read-only (MONTH_CONFIRMED).
-- Returns {year_month, minimum_hourly, rows} with the premium breakdown, probation and the applicable minimum per row.
create or replace function public.generate_payroll(p_year_month text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_first date := public.ss_month_first(p_year_month);
  v_rows jsonb;
begin
  if exists (select 1 from public.payroll p where p.year_month = p_year_month and p.status = 'CONFIRMED') then
    raise exception using message = 'MONTH_CONFIRMED', detail = jsonb_build_object('year_month', p_year_month)::text,
      hint = 'The payroll of this month is confirmed and read-only.';
  end if;
  v_rows := public.ss_generate_payroll(p_year_month);
  return jsonb_build_object('year_month', p_year_month,
                            'minimum_hourly', public.ss_minimum_wage(extract(year from v_first)::int),
                            'rows', v_rows);
end $$;

-- FR-16, BR-09: the owner acknowledges the minimum-wage warning of one DRAFT row (a row without a warning has nothing
-- to acknowledge and stays as it is).
create or replace function public.acknowledge_min_wage(p_year_month text, p_worker_id int) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform public.ss_month_first(p_year_month);
  if not exists (select 1 from public.payroll p
                 where p.year_month = p_year_month and p.worker_id = p_worker_id and p.status = 'DRAFT') then
    raise exception using message = 'NO_DRAFT',
      detail = jsonb_build_object('year_month', p_year_month, 'worker_id', p_worker_id)::text,
      hint = 'There is no draft row for this worker and month. Generate the draft first.';
  end if;
  update public.payroll set min_wage_ack = true
  where year_month = p_year_month and worker_id = p_worker_id and status = 'DRAFT' and min_wage_warning;
end $$;

-- FR-15, FR-16: confirm the month's DRAFT rows once every minimum-wage warning is acknowledged; confirmed rows are
-- read-only.
create or replace function public.confirm_payroll(p_year_month text) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_names jsonb;
begin
  perform public.ss_month_first(p_year_month);
  if not exists (select 1 from public.payroll p where p.year_month = p_year_month and p.status = 'DRAFT') then
    raise exception using message = 'NO_DRAFT', detail = jsonb_build_object('year_month', p_year_month)::text,
      hint = 'There is no draft to confirm. Generate the draft first.';
  end if;
  select jsonb_agg(jsonb_build_object('worker_id', w.id, 'name', w.name) order by w.id) into v_names
  from public.payroll p join public.worker w on w.id = p.worker_id
  where p.year_month = p_year_month and p.status = 'DRAFT' and p.min_wage_warning and not p.min_wage_ack;
  if v_names is not null then
    raise exception using message = 'MIN_WAGE_UNACKNOWLEDGED',
      detail = jsonb_build_object('year_month', p_year_month, 'workers', v_names)::text,
      hint = 'A worker''s hourly wage is below the minimum wage. Acknowledge the warning on the row, then confirm again.';
  end if;
  update public.payroll set status = 'CONFIRMED' where year_month = p_year_month and status = 'DRAFT';
end $$;

-- ---- UC-10 Manage workplace settings and minimum wage table ---------------------------------------------------------

-- FR-17: store name, regular employees, substitution-attendance policy (BR-06) and the yearly minimum wage rows
-- p_minimum_wages = [{year, hourly}] (null keeps the rows).
create or replace function public.update_settings(p_name text, p_regular_employees int, p_policy text,
                                                  p_minimum_wages jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_name text := btrim(p_name);
  v_row jsonb;
  v_years int[] := '{}';
  v_year int;
  v_hourly int;
begin
  if v_name is null or char_length(v_name) not between 1 and 100 then
    raise exception using message = 'SETTINGS_INVALID', detail = jsonb_build_object('field', 'name')::text,
      hint = 'Enter the store name with 1 to 100 characters.';
  end if;
  if p_regular_employees is null or p_regular_employees not between 0 and 1000 then
    raise exception using message = 'SETTINGS_INVALID',
      detail = jsonb_build_object('field', 'regular_employees', 'value', p_regular_employees)::text,
      hint = 'Enter the number of regular employees as a whole number from 0 to 1000.';
  end if;
  if p_policy is null or p_policy not in ('EXCUSED', 'ABSENT') then
    raise exception using message = 'SETTINGS_INVALID', detail = jsonb_build_object('field', 'policy', 'value', p_policy)::text,
      hint = 'Choose the substitution-attendance policy EXCUSED or ABSENT.';
  end if;
  if p_minimum_wages is not null then
    if jsonb_typeof(p_minimum_wages) <> 'array' then
      raise exception using message = 'SETTINGS_INVALID', detail = jsonb_build_object('field', 'minimum_wages')::text,
        hint = 'Send the minimum wages as a list of {year, hourly}.';
    end if;
    for v_row in select e from jsonb_array_elements(p_minimum_wages) as e loop
      v_year := case when (v_row->>'year') ~ '^\d{4}$' then (v_row->>'year')::int end;
      v_hourly := case when (v_row->>'hourly') ~ '^\d{1,9}$' then (v_row->>'hourly')::int end;
      if v_year is null or v_year not between 2000 and 2100 or v_hourly is null or v_hourly <= 0
         or v_year = any (v_years) then
        raise exception using message = 'SETTINGS_INVALID',
          detail = jsonb_build_object('field', 'minimum_wages', 'row', v_row)::text,
          hint = 'Enter one row per year (2000-2100) with the minimum hourly wage as a whole number of won.';
      end if;
      v_years := v_years || v_year;
    end loop;
  end if;
  update public.workplace set name = v_name, regular_employees = p_regular_employees,
    sub_attendance_policy = p_policy
  where id = (select wp.id from public.workplace wp order by wp.id limit 1);
  if p_minimum_wages is not null then
    -- Supabase refuses a DELETE without WHERE from the API roles' sessions (safeupdate), hence "where true".
    delete from public.minimum_wage where true;
    insert into public.minimum_wage (year, hourly)
    select (e->>'year')::int, (e->>'hourly')::int from jsonb_array_elements(p_minimum_wages) as e
    order by (e->>'year')::int;
