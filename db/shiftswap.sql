-- =====================================================================================================================
-- ShiftSwap — the database of spec v9 in one file: tables (§8), business rules as functions (§6, §9.3), security
-- (§9.6, NFR-14) and the demo data (§10). PostgreSQL 15 or later; runs unchanged on Supabase / Lovable Cloud and in
-- PGlite (tests/db). The file can be run again on the same database: it creates what is missing, replaces the
-- functions, re-creates the policies and grants, and finally rebuilds the demo data (select public.reset_demo_data()).
--
-- Conventions
--   * Every function is SECURITY DEFINER with an empty search_path and schema-qualified names. Internal helpers are
--     prefixed ss_ and cannot be executed by the API roles; pure helpers are IMMUTABLE.
--   * A refusal raises message = '<CODE>' (§9.2), detail = the parameters as JSON text, hint = an English sentence.
--   * Time line (BR-05): a shift occupies [work_date + start_time, work_date + end_time) and ends the next day when
--     end_time <= start_time. Durations are whole minutes; hours are shown as numeric with 2 decimals; money is
--     integer KRW rounded down.
--   * "Now" is public.app_now(): the demo clock while it is set, otherwise the server time in Korea (§9.4).
--   * Notifications store kind + params (names, shift, month); the screens compose the sentences.
-- =====================================================================================================================


-- =====================================================================================================================
-- 1. Tables (§8)
-- =====================================================================================================================

create table if not exists public.workplace (
  id int primary key,
  name text not null check (char_length(name) between 1 and 100),
  regular_employees int not null default 4 check (regular_employees between 0 and 1000),
  sub_attendance_policy text not null default 'EXCUSED' check (sub_attendance_policy in ('EXCUSED','ABSENT')),
  demo_clock timestamp            -- the demo clock (Korea time); null = real time (§9.4)
);

create table if not exists public.worker (
  id int generated by default as identity primary key,
  workplace_id int not null references public.workplace(id),
  role text not null check (role in ('OWNER','WORKER')),
  name text not null check (char_length(name) between 1 and 60),
  phone text check (char_length(phone) <= 30),
  hourly_wage int check (hourly_wage > 0),
  contract_start date,
  contract_end date,
  probation_end date,
  simple_labor boolean not null default false,
  active boolean not null default true
);

create table if not exists public.fixed_schedule (
  id int generated by default as identity primary key,
  worker_id int not null references public.worker(id),
  weekday int not null check (weekday between 1 and 7),
  start_time time not null,
  end_time time not null
);

create table if not exists public.shift (
  id int generated by default as identity primary key,
  work_date date not null,
  start_time time not null,
  end_time time not null,
  worker_id int not null references public.worker(id),
  original_worker_id int references public.worker(id),
  fixed_schedule_id int references public.fixed_schedule(id) on delete set null,
  status text not null default 'SCHEDULED' check (status in ('SCHEDULED','WORKED','ABSENT'))
);

create table if not exists public.sub_request (
  id int generated by default as identity primary key,
  shift_id int not null references public.shift(id),
  requester_id int not null references public.worker(id),
  acceptor_id int references public.worker(id),
  reason text check (char_length(reason) <= 200),
  deadline timestamp not null,
  status text not null check (status in ('REQUESTED','ACCEPTED','APPROVED','REJECTED','FAILED','EXPIRED','CANCELLED')),
  created_at timestamp not null,
  decided_at timestamp
);

create unique index if not exists one_open_request_per_shift on public.sub_request(shift_id)
  where status in ('REQUESTED','ACCEPTED');

create table if not exists public.sub_request_target (
  id int generated by default as identity primary key,
  sub_request_id int not null references public.sub_request(id),
  worker_id int not null references public.worker(id),
  response text not null default 'PENDING' check (response in ('PENDING','ACCEPTED','DECLINED','CLOSED')),
  responded_at timestamp,
  unique (sub_request_id, worker_id)
);

create table if not exists public.attendance (
  id int generated by default as identity primary key,
  shift_id int not null unique references public.shift(id),
  clock_in time not null,
  clock_out time not null,
  confirmed boolean not null default false
);

create table if not exists public.weekly_summary (
  id int generated by default as identity primary key,
  worker_id int not null references public.worker(id),
  week_start date not null,
  contract_hours numeric(6,2) not null,
  scheduled_hours numeric(6,2) not null,
  actual_hours numeric(6,2) not null,
  perfect_attendance boolean not null,
  holiday_eligible boolean not null,
  holiday_hours numeric(6,2) not null,
  holiday_pay int not null,
  unique (worker_id, week_start)
);

create table if not exists public.payroll (
  id int generated by default as identity primary key,
  worker_id int not null references public.worker(id),
  year_month text not null check (year_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  base_hours numeric(7,2) not null,
  base_pay int not null,
  holiday_pay int not null,
  premium_pay int not null,
  total int not null,
  min_wage_warning boolean not null default false,
  min_wage_ack boolean not null default false,
  estimated boolean not null default false,
  status text not null default 'DRAFT' check (status in ('DRAFT','CONFIRMED')),
  unique (worker_id, year_month)
);

create table if not exists public.minimum_wage (
  year int primary key,
  hourly int not null check (hourly > 0)
);

create table if not exists public.notification (
  id int generated by default as identity primary key,
  worker_id int not null references public.worker(id),
  sub_request_id int references public.sub_request(id),
  kind text not null check (kind in ('REQUEST_RECEIVED','REQUEST_ACCEPTED','TARGET_CLOSED','REQUEST_APPROVED',
    'REQUEST_REJECTED','REQUEST_EXPIRED','REQUEST_CANCELLED','REQUEST_FAILED','PAYROLL_DRAFT_READY')),
  params jsonb not null default '{}',
  created_at timestamp not null,
  read_at timestamp
);

-- Lookups of a worker's shifts around a date (overlap checks) and of a week's shifts.
create index if not exists shift_worker_date on public.shift (worker_id, work_date);
create index if not exists shift_work_date on public.shift (work_date);


