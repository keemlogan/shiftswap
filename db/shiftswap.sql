-- UC-08 / FR-14: store the weekly summaries of a week (all workers with a shift in it as current or original
-- worker, or only p_worker_ids); rows of workers without a shift that week are removed (§8). A week of a confirmed
-- month is left as stored.
create or replace function public.ss_recompute_week(p_week_start date, p_worker_ids int[] default null) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_week date := public.ss_week_start(p_week_start);
  v_calc jsonb;
  v_worker record;
begin
  if public.ss_week_frozen(v_week) then
    return;
  end if;
  delete from public.weekly_summary ws
  where ws.week_start = v_week
    and (p_worker_ids is null or ws.worker_id = any (p_worker_ids))
    and not exists (select 1 from public.shift s
                    where s.work_date between v_week and v_week + 6
                      and (s.worker_id = ws.worker_id or s.original_worker_id = ws.worker_id));
  for v_worker in
    select x.id from (
      select s.worker_id as id from public.shift s where s.work_date between v_week and v_week + 6
      union
      select s.original_worker_id from public.shift s
      where s.work_date between v_week and v_week + 6 and s.original_worker_id is not null) as x
    where p_worker_ids is null or x.id = any (p_worker_ids)
    order by x.id
  loop
    v_calc := public.ss_week_calc(v_worker.id, v_week);
    insert into public.weekly_summary (worker_id, week_start, contract_hours, scheduled_hours, actual_hours,
                                       perfect_attendance, holiday_eligible, holiday_hours, holiday_pay)
    values (v_worker.id, v_week, (v_calc->>'contract_hours')::numeric, (v_calc->>'scheduled_hours')::numeric,
            (v_calc->>'actual_hours')::numeric, (v_calc->>'perfect_attendance')::boolean,
            (v_calc->>'holiday_eligible')::boolean, (v_calc->>'holiday_hours')::numeric,
            (v_calc->>'holiday_pay')::int)
    on conflict (worker_id, week_start) do update set
      contract_hours = excluded.contract_hours, scheduled_hours = excluded.scheduled_hours,
      actual_hours = excluded.actual_hours, perfect_attendance = excluded.perfect_attendance,
      holiday_eligible = excluded.holiday_eligible, holiday_hours = excluded.holiday_hours,
      holiday_pay = excluded.holiday_pay;
  end loop;
end $$;

-- FR-05: the checks shared by add_shift and update_shift (TIME_INVALID, WORKER_INVALID, OUTSIDE_CONTRACT, OVERLAP).
create or replace function public.ss_check_shift(p_work_date date, p_start time, p_end time, p_worker_id int,
                                                 p_except int) returns void
language plpgsql stable security definer set search_path = '' as $$
declare
  v_worker public.worker;
  v_other public.shift;
begin
  if p_work_date is null or not public.ss_valid_span(p_start, p_end) then
    raise exception using message = 'TIME_INVALID',
      detail = jsonb_build_object('work_date', p_work_date, 'start_time', public.ss_hm(p_start),
                                  'end_time', public.ss_hm(p_end))::text,
      hint = 'Enter a date and times as HH:MM; a shift lasts 30 minutes to 16 hours and an end not later than the start is on the next day.';
  end if;
  select * into v_worker from public.worker where id = p_worker_id;
  if not found or v_worker.role <> 'WORKER' or not v_worker.active then
    raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('worker_id', p_worker_id)::text,
      hint = 'Choose an active worker for the shift.';
  end if;
  if (v_worker.contract_start is not null and p_work_date < v_worker.contract_start)
     or (v_worker.contract_end is not null and p_work_date > v_worker.contract_end) then
    raise exception using message = 'OUTSIDE_CONTRACT',
      detail = jsonb_build_object('worker_id', v_worker.id, 'name', v_worker.name, 'work_date', p_work_date,
                                  'contract_start', v_worker.contract_start, 'contract_end', v_worker.contract_end)::text,
      hint = format('%s has no contract on %s; choose a date within the contract period.', v_worker.name, p_work_date);
  end if;
  select * into v_other from public.shift
  where id = public.ss_overlapping_shift(v_worker.id, p_work_date, p_start, p_end, p_except);
  if found then
    raise exception using message = 'OVERLAP',
      detail = jsonb_build_object('worker_id', v_worker.id, 'name', v_worker.name, 'shift_id', v_other.id,
                                  'work_date', v_other.work_date, 'start_time', public.ss_hm(v_other.start_time),
                                  'end_time', public.ss_hm(v_other.end_time))::text,
      hint = format('%s already works %s %s-%s, which overlaps this time.', v_worker.name, v_other.work_date,
                    public.ss_hm(v_other.start_time), public.ss_hm(v_other.end_time));
  end if;
end $$;

-- BR-02 / BR-13: refuse an answer to a request that is no longer open for this candidate: ALREADY_TAKEN when another
-- candidate holds it (accepted or approved), otherwise REQUEST_CLOSED.
create or replace function public.ss_refuse_closed(p_request_id int, p_worker_id int) returns void
language plpgsql stable security definer set search_path = '' as $$
declare
  v_request public.sub_request;
  v_response text;
  v_name text;
begin
  select * into v_request from public.sub_request where id = p_request_id;
  select t.response into v_response from public.sub_request_target t
  where t.sub_request_id = p_request_id and t.worker_id = p_worker_id;
  if v_request.status in ('ACCEPTED', 'APPROVED') and v_request.acceptor_id is distinct from p_worker_id then
    select w.name into v_name from public.worker w where w.id = v_request.acceptor_id;
    raise exception using message = 'ALREADY_TAKEN',
      detail = jsonb_build_object('request_id', v_request.id, 'acceptor_id', v_request.acceptor_id,
                                  'acceptor_name', v_name)::text,
      hint = format('%s accepted first.', v_name);
  end if;
  if v_request.status in ('REQUESTED', 'ACCEPTED', 'APPROVED') then
    raise exception using message = 'REQUEST_CLOSED',
      detail = jsonb_build_object('request_id', v_request.id, 'status', v_request.status, 'response', v_response)::text,
      hint = 'You have already answered this request.';
  end if;
  raise exception using message = 'REQUEST_CLOSED',
    detail = jsonb_build_object('request_id', v_request.id, 'status', v_request.status, 'response', v_response)::text,
    hint = format('This request is %s, so it can no longer be answered.', lower(v_request.status));
end $$;

-- BR-08–BR-11: compute and store the DRAFT payroll of a month (existing DRAFT rows are replaced; the caller checks that
-- the month is not confirmed). Rows: every WORKER with paid shifts or holiday pay in the month, and every active
-- worker whose contract period meets the month. Returns the rows with their details.
create or replace function public.ss_generate_payroll(p_year_month text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_first date := public.ss_month_first(p_year_month);
  v_last date := (public.ss_month_first(p_year_month) + interval '1 month')::date - 1;
  v_from date;
  v_to date;
  v_employees int;
  v_minimum int;
  v_weeks date[];
  v_week date;
  v_rows jsonb := '[]'::jsonb;
  v_worker record;
  v_minutes int;
  v_estimated boolean;
  v_intervals jsonb;
  v_holiday_pay int;
  v_premium jsonb;
  v_base_pay int;
  v_premium_pay int;
  v_probation boolean;
  v_applicable numeric;
  v_warning boolean;
  v_id int;
begin
  v_from := public.ss_week_start(v_first);
  v_to := public.ss_week_start(v_last) + 6;
  v_minimum := public.ss_minimum_wage(extract(year from v_first)::int);
  select wp.regular_employees into v_employees from public.workplace wp order by wp.id limit 1;
  -- BR-11: holiday pay comes from the weeks whose Sunday falls in the month; they are recomputed first.
  select coalesce(array_agg(v_first + g.n - 6 order by g.n), '{}') into v_weeks
  from generate_series(0, v_last - v_first) as g(n)
  where extract(isodow from v_first + g.n) = 7;
  foreach v_week in array v_weeks loop
    perform public.ss_recompute_week(v_week);
  end loop;
  delete from public.payroll where year_month = p_year_month and status = 'DRAFT';
  for v_worker in
    select k.id, k.name, coalesce(k.hourly_wage, 0) as wage, k.contract_start
    from public.worker k
    where k.role = 'WORKER'
      and not exists (select 1 from public.payroll p where p.worker_id = k.id and p.year_month = p_year_month)
      and (exists (select 1 from public.shift s where s.worker_id = k.id and s.status <> 'ABSENT'
                   and s.work_date between v_first and v_last)
           or exists (select 1 from public.weekly_summary ws where ws.worker_id = k.id
                      and ws.week_start = any (v_weeks) and ws.holiday_pay > 0)
           or (k.active and k.contract_start is not null and k.contract_start <= v_last
               and (k.contract_end is null or k.contract_end >= v_first)))
    order by k.id
  loop
    -- BR-11: WORKED shifts with their recorded minutes, SCHEDULED shifts with their scheduled minutes (estimated),
    -- ABSENT shifts 0. The days of the first and last ISO weeks outside the month are BR-08 context only.
    select coalesce(sum(public.ss_range_minutes(x.r)) filter (where x.work_date between v_first and v_last), 0),
           coalesce(bool_or(x.estimated) filter (where x.work_date between v_first and v_last), false),
           coalesce(jsonb_agg(jsonb_build_object('work_date', x.work_date, 'start', lower(x.r), 'end', upper(x.r))
                              order by lower(x.r)), '[]'::jsonb)
      into v_minutes, v_estimated, v_intervals
    from (select s.work_date, s.status = 'SCHEDULED' as estimated,
                 case when s.status = 'WORKED' and a.id is not null
                      then public.ss_attendance_range(s.work_date, s.start_time, s.end_time, a.clock_in, a.clock_out)
                      else public.ss_range(s.work_date, s.start_time, s.end_time) end as r
          from public.shift s left join public.attendance a on a.shift_id = s.id
          where s.worker_id = v_worker.id and s.status <> 'ABSENT' and s.work_date between v_from and v_to) as x;
    select coalesce(sum(ws.holiday_pay), 0)::int into v_holiday_pay
    from public.weekly_summary ws where ws.worker_id = v_worker.id and ws.week_start = any (v_weeks);
    v_premium := public.ss_premium(v_intervals, public.ss_contract_minutes(v_worker.id), v_employees, v_first, v_last);
    v_base_pay := floor(v_minutes::numeric * v_worker.wage / 60);
    v_premium_pay := floor((v_premium->>'total_minutes')::numeric * v_worker.wage / 120);
    -- BR-09 / BR-10: evaluated on the first day of the month, or on contract_start if later.
    v_probation := public.ss_probation(v_worker.id, greatest(v_first, v_worker.contract_start));
    v_applicable := case when v_minimum is null then null when v_probation then v_minimum * 0.9 else v_minimum end;
    v_warning := v_applicable is not null and v_worker.wage < v_applicable;
    insert into public.payroll (worker_id, year_month, base_hours, base_pay, holiday_pay, premium_pay, total,
                                min_wage_warning, min_wage_ack, estimated, status)
    values (v_worker.id, p_year_month, round(v_minutes / 60.0, 2), v_base_pay, v_holiday_pay, v_premium_pay,
            v_base_pay + v_holiday_pay + v_premium_pay, v_warning, false, v_estimated, 'DRAFT')
    returning id into v_id;
    v_rows := v_rows || jsonb_build_array(jsonb_build_object(
      'id', v_id, 'worker_id', v_worker.id, 'name', v_worker.name, 'hourly_wage', v_worker.wage,
      'base_minutes', v_minutes, 'base_hours', round(v_minutes / 60.0, 2), 'base_pay', v_base_pay,
      'holiday_pay', v_holiday_pay,
      'premium', v_premium, 'premium_hours', round((v_premium->>'total_minutes')::int / 60.0, 2),
      'premium_pay', v_premium_pay,
      'total', v_base_pay + v_holiday_pay + v_premium_pay,
      'minimum_hourly', v_minimum, 'probation', v_probation, 'applicable_minimum', v_applicable,
      'min_wage_warning', v_warning, 'min_wage_ack', false, 'estimated', v_estimated, 'status', 'DRAFT'));
  end loop;
  return v_rows;
end $$;

-- UC-14 / BR-14: every month from the earliest contract month to the month before now that has no payroll row gets
-- its DRAFT (exactly as generate_payroll) and one PAYROLL_DRAFT_READY notification for the owner. Existing rows are
-- never overwritten and nothing is confirmed. Returns the drafted months.
create or replace function public.ss_prepare_drafts() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_month date;
  v_year_month text;
  v_months jsonb := '[]'::jsonb;
begin
  select date_trunc('month', min(w.contract_start)::timestamp)::date into v_month
  from public.worker w where w.role = 'WORKER';
  if v_month is null then
    return v_months;
  end if;
  while v_month < date_trunc('month', v_now)::date loop
    v_year_month := to_char(v_month::timestamp, 'YYYY-MM');
    if not exists (select 1 from public.payroll p where p.year_month = v_year_month)
       and jsonb_array_length(public.ss_generate_payroll(v_year_month)) > 0 then
      perform public.ss_notify(public.ss_owner_id(), null, 'PAYROLL_DRAFT_READY',
                               jsonb_build_object('year_month', v_year_month));
      v_months := v_months || jsonb_build_array(v_year_month);
    end if;
    v_month := (v_month + interval '1 month')::date;
  end loop;
  return v_months;
end $$;


