begin
  if not exists (select 1 from public.shift s where s.id = p_shift_id) then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
