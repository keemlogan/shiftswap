-- UC-03: one shift with its attendance, request history and the owner's allowed actions.
create or replace function public.shift_detail(p_shift_id int) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_shift public.shift;
  v_attendance public.attendance;
  v_open boolean;
  v_history boolean;
begin
  select * into v_shift from public.shift where id = p_shift_id;
  if not found then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
  select * into v_attendance from public.attendance where shift_id = v_shift.id;
  v_open := exists (select 1 from public.sub_request r
                    where r.shift_id = v_shift.id and r.status in ('REQUESTED', 'ACCEPTED'));
  v_history := v_attendance.id is not null
               or exists (select 1 from public.sub_request r where r.shift_id = v_shift.id);
  return public.ss_shift_json(v_shift.id) || jsonb_build_object(
    'attendance', case when v_attendance.id is null then null else jsonb_build_object(
      'clock_in', public.ss_hm(v_attendance.clock_in), 'clock_out', public.ss_hm(v_attendance.clock_out),
      'confirmed', v_attendance.confirmed,
      'minutes', public.ss_range_minutes(public.ss_attendance_range(v_shift.work_date, v_shift.start_time,
                   v_shift.end_time, v_attendance.clock_in, v_attendance.clock_out))) end,
    'requests', coalesce((
      select jsonb_agg(public.ss_request_params(r.id) || jsonb_build_object(
                         'created_at', r.created_at, 'decided_at', r.decided_at,
                         'targets', public.ss_targets_json(r.id)) order by r.created_at, r.id)
      from public.sub_request r where r.shift_id = v_shift.id), '[]'::jsonb),
    'actions', jsonb_build_object(
      'can_edit', not v_open,
      'can_delete', not v_history,
      'can_mark_absent', v_shift.status = 'SCHEDULED' and v_shift.work_date + v_shift.start_time <= v_now,
      'can_confirm_attendance', v_shift.status = 'SCHEDULED' and v_attendance.id is not null
                                and not v_attendance.confirmed));
end $$;

