                                else jsonb_build_object('id', ac.id, 'name', ac.name) end,
               'created_at', r.created_at, 'decided_at', r.decided_at,
               'targets', public.ss_targets_json(r.id))
             order by r.created_at desc, r.id desc)
      from public.sub_request r
      join public.shift s on s.id = r.shift_id
      left join public.worker ac on ac.id = r.acceptor_id
