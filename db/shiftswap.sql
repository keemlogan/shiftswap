-- UC-04 / UC-05 / UC-12 Swaps: the worker's own requests (newest first) and the requests the worker was asked for
-- (open ones first, by deadline), with the effect of taking an open one on the worker's week.
create or replace function public.my_requests(p_worker_id int) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.worker w where w.id = p_worker_id) then
