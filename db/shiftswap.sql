-- UC-09 Pay → Monthly: the stored rows of a month (nothing is generated) with names, flags and the probation minimum
-- where BR-10 applies; the month status (NONE / DRAFT / CONFIRMED), unacknowledged warnings and totals.
create or replace function public.payroll_month(p_year_month text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_first date := public.ss_month_first(p_year_month);
  v_minimum int;
begin
  v_minimum := public.ss_minimum_wage(extract(year from v_first)::int);
  return (
    select jsonb_build_object(
      'year_month', p_year_month,
      'status', case when count(p.id) = 0 then 'NONE' when bool_or(p.status = 'DRAFT') then 'DRAFT'
                     else 'CONFIRMED' end,
      'auto_prepared', exists (select 1 from public.notification n
                               where n.kind = 'PAYROLL_DRAFT_READY' and n.params->>'year_month' = p_year_month),
      'minimum_hourly', v_minimum,
      'unacknowledged_warnings', count(p.id) filter (where p.status = 'DRAFT' and p.min_wage_warning
                                                     and not p.min_wage_ack),
      'rows', coalesce(jsonb_agg(jsonb_build_object(
                'id', p.id, 'worker_id', p.worker_id, 'name', w.name, 'hourly_wage', w.hourly_wage,
                'base_hours', p.base_hours, 'base_pay', p.base_pay, 'holiday_pay', p.holiday_pay,
                'premium_pay', p.premium_pay, 'total', p.total,
                'min_wage_warning', p.min_wage_warning, 'min_wage_ack', p.min_wage_ack,
                'estimated', p.estimated, 'status', p.status,
                'probation_minimum', case when v_minimum is not null
                                               and public.ss_probation(w.id, greatest(v_first, w.contract_start))
                                          then v_minimum * 0.9 end)
                order by p.worker_id) filter (where p.id is not null), '[]'::jsonb),
      'totals', jsonb_build_object('base_hours', coalesce(sum(p.base_hours), 0),
                                   'base_pay', coalesce(sum(p.base_pay), 0),
                                   'holiday_pay', coalesce(sum(p.holiday_pay), 0),
                                   'premium_pay', coalesce(sum(p.premium_pay), 0),
                                   'total', coalesce(sum(p.total), 0)))
    from public.payroll p join public.worker w on w.id = p.worker_id
    where p.year_month = p_year_month);
end $$;

-- UC-09 / UC-14: every month that has payroll rows, ascending, with its status and whether the System Clock prepared
-- its draft (a PAYROLL_DRAFT_READY notification exists for it).
create or replace function public.payroll_months() returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('year_month', m.year_month, 'status', m.status,
                                               'auto_prepared', m.auto_prepared) order by m.year_month), '[]'::jsonb)
  from (select p.year_month,
               case when bool_or(p.status = 'DRAFT') then 'DRAFT' else 'CONFIRMED' end as status,
               exists (select 1 from public.notification n
                       where n.kind = 'PAYROLL_DRAFT_READY' and n.params->>'year_month' = p.year_month) as auto_prepared
        from public.payroll p group by p.year_month) as m
$$;

-- FR-21: the worker's inbox, newest first, with the unread count.
create or replace function public.notifications(p_worker_id int) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.worker w where w.id = p_worker_id) then
    raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('worker_id', p_worker_id)::text,
      hint = 'Choose a demo account.';
  end if;
  return jsonb_build_object(
    'items', coalesce((
      select jsonb_agg(jsonb_build_object('id', n.id, 'kind', n.kind, 'params', n.params,
                                          'sub_request_id', n.sub_request_id, 'created_at', n.created_at,
                                          'read_at', n.read_at) order by n.created_at desc, n.id desc)
      from public.notification n where n.worker_id = p_worker_id), '[]'::jsonb),
    'unread', (select count(*) from public.notification n where n.worker_id = p_worker_id and n.read_at is null));
end $$;

