-- Set the demo clock (Korea time); null switches to real time. Returns the new "now".
create or replace function public.set_demo_clock(p_at timestamp) returns timestamp
language plpgsql security definer set search_path = '' as $$
begin
  update public.workplace set demo_clock = p_at
