-- Worker Home: requests for me (with the effect of accepting on my week), requests taken by someone else, my open
-- requests with the answers, my FAILED requests to acknowledge, next shift, this week's hours and shifts to record.
create or replace function public.worker_home(p_worker_id int) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_worker public.worker;
  v_week date := public.ss_week_start(public.app_now()::date);
begin
  select * into v_worker from public.worker where id = p_worker_id;
  if not found or v_worker.role <> 'WORKER' then
    raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('worker_id', p_worker_id)::text,
      hint = 'Choose a worker account.';
  end if;
  return jsonb_build_object(
    'worker', jsonb_build_object('id', v_worker.id, 'name', v_worker.name),
    'now', v_now, 'today', v_now::date,
    'incoming', coalesce((
      select jsonb_agg(public.ss_request_params(r.id)
                       || jsonb_build_object('effect', public.ss_swap_effect(r.shift_id, v_worker.id)->'acceptor')
                       order by r.deadline, r.id)
      from public.sub_request r join public.sub_request_target t on t.sub_request_id = r.id
      where t.worker_id = v_worker.id and t.response = 'PENDING' and r.status = 'REQUESTED'), '[]'::jsonb),
    'taken', coalesce((
      select jsonb_agg(public.ss_request_params(r.id) order by r.deadline, r.id)
      from public.sub_request r join public.sub_request_target t on t.sub_request_id = r.id
      where t.worker_id = v_worker.id and t.response = 'CLOSED' and r.status = 'ACCEPTED'
        and r.acceptor_id <> v_worker.id), '[]'::jsonb),
    'my_open', coalesce((
      select jsonb_agg(public.ss_request_params(r.id) || jsonb_build_object('targets', public.ss_targets_json(r.id))
                       order by s.work_date, s.start_time, r.id)
      from public.sub_request r join public.shift s on s.id = r.shift_id
      where r.requester_id = v_worker.id and r.status in ('REQUESTED', 'ACCEPTED')), '[]'::jsonb),
    'failed', coalesce((
      select jsonb_agg(jsonb_build_object('notification_id', n.id) || public.ss_request_params(r.id) order by n.id)
      from public.notification n join public.sub_request r on r.id = n.sub_request_id
      where n.worker_id = v_worker.id and n.kind = 'REQUEST_FAILED' and n.read_at is null
        and r.requester_id = v_worker.id), '[]'::jsonb),
    'next_shift', (
      select public.ss_shift_json(s.id) from public.shift s
      where s.worker_id = v_worker.id and s.status = 'SCHEDULED' and s.work_date + s.start_time > v_now
      order by s.work_date, s.start_time, s.id limit 1),
    'week', public.ss_week_calc(v_worker.id, v_week),
    'to_record', coalesce((
      select jsonb_agg(public.ss_shift_json(s.id) order by s.work_date, s.start_time, s.id)
      from public.shift s
      where s.worker_id = v_worker.id and s.status = 'SCHEDULED'
        and public.ss_end_ts(s.work_date, s.start_time, s.end_time) <= v_now
        and not exists (select 1 from public.attendance a where a.shift_id = s.id)), '[]'::jsonb),
    'unread', (select count(*) from public.notification n where n.worker_id = v_worker.id and n.read_at is null));
end $$;

