-- FR-06–FR-08: validate (BR-03), create the request, one target and one REQUEST_RECEIVED per eligible candidate
-- (BR-01); without candidates the request ends FAILED at once and requester and owner receive REQUEST_FAILED (BR-13).
-- Returns {id, status, candidates}.
create or replace function public.create_sub_request(p_shift_id int, p_requester_id int, p_reason text,
                                                     p_deadline timestamp) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_shift public.shift;
  v_start timestamp;
  v_open int;
  v_id int;
  v_candidates jsonb;
  v_candidate jsonb;
  v_params jsonb;
  v_status text := 'REQUESTED';
begin
  select * into v_shift from public.shift where id = p_shift_id for update;
  if not found then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
  if v_shift.worker_id is distinct from p_requester_id then
    raise exception using message = 'NOT_YOUR_SHIFT',
      detail = jsonb_build_object('shift_id', v_shift.id, 'worker_id', p_requester_id)::text,
      hint = 'You can only request a substitute for your own shift.';
  end if;
  if v_shift.status <> 'SCHEDULED' then
    raise exception using message = 'NOT_SCHEDULED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'status', v_shift.status)::text,
      hint = 'This shift is already closed (worked or absent), so it cannot be handed over.';
  end if;
  v_start := v_shift.work_date + v_shift.start_time;
  if v_start <= v_now then
    raise exception using message = 'SHIFT_STARTED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'start_at', v_start)::text,
      hint = 'This shift has already started. Talk to the owner directly.';
  end if;
  select r.id into v_open from public.sub_request r
  where r.shift_id = v_shift.id and r.status in ('REQUESTED', 'ACCEPTED');
  if v_open is not null then
    raise exception using message = 'OPEN_REQUEST_EXISTS',
      detail = jsonb_build_object('shift_id', v_shift.id, 'request_id', v_open)::text,
      hint = 'This shift already has an open request. Cancel it first if you want to change it.';
  end if;
  if p_deadline is null or p_deadline <= v_now then
    raise exception using message = 'DEADLINE_INVALID',
      detail = jsonb_build_object('deadline', p_deadline, 'now', v_now, 'start_at', v_start)::text,
      hint = 'The reply deadline must be later than now.';
  end if;
  if p_deadline > v_start then
    raise exception using message = 'DEADLINE_INVALID',
      detail = jsonb_build_object('deadline', p_deadline, 'now', v_now, 'start_at', v_start)::text,
      hint = 'The reply deadline must not be later than the start of the shift.';
  end if;
  insert into public.sub_request (shift_id, requester_id, reason, deadline, status, created_at)
  values (v_shift.id, p_requester_id, nullif(btrim(p_reason), ''), p_deadline, 'REQUESTED', v_now)
  returning id into v_id;
  v_candidates := public.ss_candidates(v_shift.id, p_requester_id);
  v_params := public.ss_request_params(v_id);
  for v_candidate in select e from jsonb_array_elements(v_candidates) as e loop
    insert into public.sub_request_target (sub_request_id, worker_id) values (v_id, (v_candidate->>'id')::int);
    perform public.ss_notify((v_candidate->>'id')::int, v_id, 'REQUEST_RECEIVED', v_params);
  end loop;
  if jsonb_array_length(v_candidates) = 0 then
    update public.sub_request set status = 'FAILED', decided_at = v_now where id = v_id;
    v_status := 'FAILED';
    v_params := public.ss_request_params(v_id);
    perform public.ss_notify(p_requester_id, v_id, 'REQUEST_FAILED', v_params);
    perform public.ss_notify(public.ss_owner_id(), v_id, 'REQUEST_FAILED', v_params);
  end if;
  return jsonb_build_object('id', v_id, 'status', v_status, 'candidates', v_candidates);
end $$;

-- ---- UC-05 Respond to substitute request ----------------------------------------------------------------------------

-- FR-09, FR-10, BR-12, BR-02: expiry first; then the one conditional UPDATE decides the first acceptance. A later
-- acceptance is refused with ALREADY_TAKEN naming the acceptor; a closed request with REQUEST_CLOSED. On success the
-- other pending targets are closed (TARGET_CLOSED) and requester and owner receive REQUEST_ACCEPTED.
create or replace function public.accept_sub_request(p_request_id int, p_worker_id int) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_request public.sub_request;
  v_target public.sub_request_target;
  v_shift public.shift;
  v_busy public.shift;
  v_closed int[];
  v_worker int;
  v_params jsonb;
begin
  if not exists (select 1 from public.sub_request r where r.id = p_request_id) then
    raise exception using message = 'REQUEST_NOT_FOUND', detail = jsonb_build_object('request_id', p_request_id)::text,
      hint = 'This request does not exist. Reload the page.';
  end if;
  perform public.expire_overdue_requests();
  select * into v_request from public.sub_request where id = p_request_id;
  select * into v_target from public.sub_request_target
  where sub_request_id = v_request.id and worker_id = p_worker_id;
  if not found then
    raise exception using message = 'NOT_A_TARGET',
      detail = jsonb_build_object('request_id', v_request.id, 'worker_id', p_worker_id)::text,
      hint = 'You were not asked to cover this shift.';
  end if;
  if v_request.status = 'EXPIRED' then
    raise exception using message = 'REQUEST_CLOSED',
      detail = jsonb_build_object('request_id', v_request.id, 'status', 'EXPIRED')::text,
      hint = 'This request expired at its deadline or when the shift started, so it can no longer be accepted.';
  end if;
  if v_request.status <> 'REQUESTED' or v_target.response <> 'PENDING' then
    perform public.ss_refuse_closed(v_request.id, p_worker_id);
  end if;
  select * into v_shift from public.shift where id = v_request.shift_id;
  select * into v_busy from public.shift
  where id = public.ss_overlapping_shift(p_worker_id, v_shift.work_date, v_shift.start_time, v_shift.end_time,
                                         v_shift.id);
  if found then
    raise exception using message = 'ACCEPTOR_BUSY',
      detail = jsonb_build_object('request_id', v_request.id, 'worker_id', p_worker_id, 'shift_id', v_busy.id,
                                  'work_date', v_busy.work_date, 'start_time', public.ss_hm(v_busy.start_time),
                                  'end_time', public.ss_hm(v_busy.end_time))::text,
      hint = format('You already work %s %s-%s, which overlaps this shift.', v_busy.work_date,
                    public.ss_hm(v_busy.start_time), public.ss_hm(v_busy.end_time));
  end if;
  -- BR-02: the first acceptance wins. Under READ COMMITTED a concurrent second UPDATE of the row waits, re-checks
  -- the WHERE clause on the new row version and changes nothing (§9.5).
  update public.sub_request q set status = 'ACCEPTED', acceptor_id = p_worker_id
  where q.id = v_request.id and q.status = 'REQUESTED' and q.deadline > v_now
    and exists (select 1 from public.shift s where s.id = q.shift_id and s.work_date + s.start_time > v_now);
  if not found then
    perform public.ss_refuse_closed(v_request.id, p_worker_id);
  end if;
  update public.sub_request_target set response = 'ACCEPTED', responded_at = v_now where id = v_target.id;
  with closed as (
    update public.sub_request_target set response = 'CLOSED', responded_at = v_now
    where sub_request_id = v_request.id and response = 'PENDING'
    returning worker_id
  )
  select coalesce(array_agg(c.worker_id order by c.worker_id), '{}') into v_closed from closed c;
  v_params := public.ss_request_params(v_request.id);
  foreach v_worker in array v_closed loop
    perform public.ss_notify(v_worker, v_request.id, 'TARGET_CLOSED', v_params);
  end loop;
  perform public.ss_notify(v_request.requester_id, v_request.id, 'REQUEST_ACCEPTED', v_params);
  perform public.ss_notify(public.ss_owner_id(), v_request.id, 'REQUEST_ACCEPTED', v_params);
  return jsonb_build_object('id', v_request.id, 'status', 'ACCEPTED', 'acceptor_id', p_worker_id,
                            'acceptor_name', v_params->>'acceptor_name');
end $$;

-- FR-22, BR-13: a candidate answers "can't" (DECLINED). The answer that leaves every target DECLINED ends the request
-- FAILED; requester and owner receive REQUEST_FAILED. A single "can't" notifies no one. Returns {id, status}.
create or replace function public.decline_sub_request(p_request_id int, p_worker_id int) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_request public.sub_request;
  v_target public.sub_request_target;
  v_status text;
  v_params jsonb;
begin
  if not exists (select 1 from public.sub_request r where r.id = p_request_id) then
    raise exception using message = 'REQUEST_NOT_FOUND', detail = jsonb_build_object('request_id', p_request_id)::text,
      hint = 'This request does not exist. Reload the page.';
  end if;
  perform public.expire_overdue_requests();
  if not exists (select 1 from public.sub_request_target t
                 where t.sub_request_id = p_request_id and t.worker_id = p_worker_id) then
    raise exception using message = 'NOT_A_TARGET',
      detail = jsonb_build_object('request_id', p_request_id, 'worker_id', p_worker_id)::text,
      hint = 'You were not asked to cover this shift.';
  end if;
  -- The request row is locked before its targets, in the same order as accept, cancel and expiry.
  select * into v_request from public.sub_request where id = p_request_id for update;
  select * into v_target from public.sub_request_target
  where sub_request_id = v_request.id and worker_id = p_worker_id;
  if v_request.status <> 'REQUESTED' or v_target.response <> 'PENDING' then
    perform public.ss_refuse_closed(v_request.id, p_worker_id);
  end if;
  update public.sub_request_target set response = 'DECLINED', responded_at = v_now where id = v_target.id;
  v_status := v_request.status;
  if not exists (select 1 from public.sub_request_target t
                 where t.sub_request_id = v_request.id and t.response <> 'DECLINED') then
    update public.sub_request set status = 'FAILED', decided_at = v_now
    where id = v_request.id and status = 'REQUESTED';
    v_status := 'FAILED';
    v_params := public.ss_request_params(v_request.id);
    perform public.ss_notify(v_request.requester_id, v_request.id, 'REQUEST_FAILED', v_params);
    perform public.ss_notify(public.ss_owner_id(), v_request.id, 'REQUEST_FAILED', v_params);
  end if;
  return jsonb_build_object('id', v_request.id, 'status', v_status);
end $$;

