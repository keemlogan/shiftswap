      select jsonb_agg(jsonb_build_object(
               'id', r.id, 'status', r.status,
               'requester', jsonb_build_object('id', rq.id, 'name', rq.name),
               'shift', jsonb_build_object('id', s.id, 'work_date', s.work_date,
                                           'start_time', public.ss_hm(s.start_time),
                                           'end_time', public.ss_hm(s.end_time)),
               'reason', r.reason, 'deadline', r.deadline, 'my_response', t.response,
               'acceptor', case when ac.id is null then null
                                else jsonb_build_object('id', ac.id, 'name', ac.name) end,
