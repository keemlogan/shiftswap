                 from (select public.ss_swap_effect(r.shift_id, p_worker_id)->'acceptor' as v) as e) end)
             order by (r.status in ('REQUESTED', 'ACCEPTED')) desc,
                      case when r.status in ('REQUESTED', 'ACCEPTED') then r.deadline end,
                      r.created_at desc, r.id desc)
      from public.sub_request r
      join public.sub_request_target t on t.sub_request_id = r.id and t.worker_id = p_worker_id
      join public.shift s on s.id = r.shift_id
      join public.worker rq on rq.id = r.requester_id
      left join public.worker ac on ac.id = r.acceptor_id), '[]'::jsonb));
end $$;

