-- 'HH:MM' of a time (null stays null).
create or replace function public.ss_hm(p_time time) returns text
language sql immutable set search_path = '' as $$
  select substr(p_time::text, 1, 5)
$$;

-- BR-05: minutes from p_start to p_end; an end not later than the start is on the next day.
create or replace function public.ss_minutes(p_start time, p_end time) returns int
language sql immutable set search_path = '' as $$
  select (extract(epoch from (p_end - p_start)) / 60)::int + case when p_end <= p_start then 1440 else 0 end
$$;

-- BR-05: the end of a shift on the actual time line.
create or replace function public.ss_end_ts(p_date date, p_start time, p_end time) returns timestamp
language sql immutable set search_path = '' as $$
  select p_date + p_start + make_interval(mins => public.ss_minutes(p_start, p_end))
$$;

-- BR-05: the interval [start, end) of a shift on the actual time line.
create or replace function public.ss_range(p_date date, p_start time, p_end time) returns tsrange
language sql immutable set search_path = '' as $$
  select tsrange(p_date + p_start, public.ss_end_ts(p_date, p_start, p_end), '[)')
$$;

-- Length of a time-line interval in minutes.
create or replace function public.ss_range_minutes(p_range tsrange) returns int
language sql immutable set search_path = '' as $$
  select (extract(epoch from (upper(p_range) - lower(p_range))) / 60)::int
$$;

-- BR-05: the Monday of the ISO week of a date.
create or replace function public.ss_week_start(p_date date) returns date
language sql immutable set search_path = '' as $$
  select p_date - (extract(isodow from p_date)::int - 1)
$$;

-- BR-05 / FR-02: two fixed weekly slots overlap on the weekly time line. Each slot is placed in the week of Monday
-- 2001-01-01 and also compared one week later, so Sunday 22:00–02:00 meets Monday 01:00–05:00.
create or replace function public.ss_slots_overlap(p_day1 int, p_start1 time, p_end1 time,
                                                   p_day2 int, p_start2 time, p_end2 time) returns boolean
language sql immutable set search_path = '' as $$
  select public.ss_range(date '2001-01-01' + (p_day1 - 1), p_start1, p_end1)
           && public.ss_range(date '2001-01-01' + (p_day2 - 1), p_start2, p_end2)
      or public.ss_range(date '2001-01-01' + (p_day1 - 1), p_start1, p_end1)
           && public.ss_range(date '2001-01-08' + (p_day2 - 1), p_start2, p_end2)
      or public.ss_range(date '2001-01-08' + (p_day1 - 1), p_start1, p_end1)
           && public.ss_range(date '2001-01-01' + (p_day2 - 1), p_start2, p_end2)
$$;

-- A time the system accepts for shifts and clock times: whole minutes from 00:00 to 23:59.
create or replace function public.ss_valid_time(p_time time) returns boolean
language sql immutable set search_path = '' as $$
  select p_time is not null and p_time < time '24:00' and extract(second from p_time) = 0
$$;

-- BR-05: a shift or fixed slot lasts between 30 minutes and 16 hours (start = end would be 24 hours).
create or replace function public.ss_valid_span(p_start time, p_end time) returns boolean
language sql immutable set search_path = '' as $$
  select coalesce(public.ss_valid_time(p_start) and public.ss_valid_time(p_end)
                  and public.ss_minutes(p_start, p_end) between 30 and 960, false)
$$;

-- Text 'HH:MM' (or 'HH:MM:SS') to a time; null when it is not a time of day.
create or replace function public.ss_parse_time(p_text text) returns time
language plpgsql immutable set search_path = '' as $$
begin
  if p_text is null or p_text !~ '^\s*\d{1,2}:\d{2}(:\d{2})?\s*$' then
    return null;
  end if;
  return p_text::time;
exception when others then
  return null;
end $$;

-- 'YYYY-MM' to the first day of the month, or MONTH_INVALID.
create or replace function public.ss_month_first(p_year_month text) returns date
language plpgsql immutable set search_path = '' as $$
begin
  if p_year_month is null or p_year_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then
    raise exception using message = 'MONTH_INVALID', detail = jsonb_build_object('year_month', p_year_month)::text,
      hint = 'Choose a month in the form YYYY-MM.';
  end if;
  return make_date(left(p_year_month, 4)::int, right(p_year_month, 2)::int, 1);
end $$;

-- BR-08 (iii): minutes of [p_start, p_end) that fall between 22:00 and 06:00 of the next day on the actual time line.
create or replace function public.ss_night_minutes(p_start timestamp, p_end timestamp) returns int
language sql immutable set search_path = '' as $$
  select coalesce(sum(greatest(0, extract(epoch from (least(p_end, w.d + interval '30 hours')
                                                     - greatest(p_start, w.d + interval '22 hours'))) / 60)), 0)::int
  from (select p_start::date::timestamp + k.n * interval '1 day' as d from (values (-1), (0), (1)) as k(n)) as w
$$;

-- BR-06 (a) / BR-07: holiday-allowance hours for weekly contractual hours C: min(C, 40) / 40 × 8 rounded to
-- 2 decimals when C >= 15, otherwise 0. Perfect attendance (BR-06 b) is checked by the caller.
create or replace function public.ss_holiday_hours(p_contract_hours numeric) returns numeric
language sql immutable set search_path = '' as $$
  select case when p_contract_hours >= 15 then round(least(p_contract_hours, 40) / 40 * 8, 2) else 0.00 end
$$;

-- BR-08: premium minutes of one worker.
--   p_shifts: [{work_date, start, end}] — paid intervals on the time line (scheduled or recorded); every hour counts on
--   its shift's work date. Days outside [p_paid_from, p_paid_to] are context: they only decide where the first C and
--   the first 40 hours of their ISO week end and are not paid (rule (e) for a monthly payroll).
--   (i) a work date's minutes beyond 8 h; (ii) a week's regular minutes (at most 8 h a day) beyond 40 h, in time
--   order; (iii) night minutes 22:00–06:00; (iv) part-time (0 < C < 40 h): minutes after the first C minutes of the
--   ISO week in time order, an hour counted once with (i) and (ii) (rule (d)). For a part-time worker (ii) lies inside
--   (iv), so a day's overtime is max(daily beyond 8 h, beyond contract). Zero below five regular employees.
create or replace function public.ss_premium(p_shifts jsonb, p_contract_minutes int, p_regular_employees int,
                                             p_paid_from date, p_paid_to date) returns jsonb
language plpgsql immutable set search_path = '' as $$
declare
  v_part_time boolean := coalesce(p_contract_minutes, 0) > 0 and p_contract_minutes < 2400;
  v_daily int := 0;
  v_weekly int := 0;
  v_part int := 0;
  v_night int := 0;
  v_week date;
  v_before int := 0;      -- minutes of the ISO week on earlier days
  v_before_reg int := 0;  -- regular minutes (at most 480 a day) of the ISO week on earlier days
  v_extra int;
  v_reg int;
  v_over40 int;
  v_over_c int;
  v_day record;
begin
  if coalesce(p_regular_employees, 0) >= 5 then
    for v_day in
      select x.work_date, sum(x.minutes)::int as minutes, sum(x.night)::int as night
      from (select (e->>'work_date')::date as work_date,
                   (extract(epoch from ((e->>'end')::timestamp - (e->>'start')::timestamp)) / 60)::int as minutes,
                   public.ss_night_minutes((e->>'start')::timestamp, (e->>'end')::timestamp) as night
            from jsonb_array_elements(coalesce(p_shifts, '[]'::jsonb)) as e) as x
      group by x.work_date
      order by x.work_date
    loop
      if v_week is distinct from public.ss_week_start(v_day.work_date) then
        v_week := public.ss_week_start(v_day.work_date);
        v_before := 0;
        v_before_reg := 0;
      end if;
      v_extra := greatest(0, v_day.minutes - 480);
      v_reg := v_day.minutes - v_extra;
      if v_day.work_date between p_paid_from and p_paid_to then
        v_over40 := greatest(0, v_before_reg + v_reg - greatest(2400, v_before_reg));
        v_daily := v_daily + v_extra;
        v_weekly := v_weekly + v_over40;
        v_night := v_night + v_day.night;
        if v_part_time then
          v_over_c := greatest(0, v_before + v_day.minutes - greatest(p_contract_minutes, v_before));
          v_part := v_part + greatest(0, v_over_c - v_extra) - v_over40;
        end if;
      end if;
      v_before := v_before + v_day.minutes;
      v_before_reg := v_before_reg + v_reg;
    end loop;
  end if;
  return jsonb_build_object('daily_minutes', v_daily, 'weekly_minutes', v_weekly, 'night_minutes', v_night,
                            'part_time_minutes', v_part, 'total_minutes', v_daily + v_weekly + v_night + v_part);
end $$;

-- BR-17: the recorded interval of a shift on its time line. The clock-in is the time on the day before, the day of or
-- the day after the work date that lies in the plausible window [start − 2 h, end + 4 h) (the window is shorter than a
-- day, so at most one does); without one it is placed as written (on the work date, or on the next day for a time
-- earlier than the start of a shift that ends the next day) and the plausibility check refuses it. The clock-out is on
-- the clock-in's date, or on the next day when it is not later than the clock-in.
create or replace function public.ss_attendance_range(p_date date, p_start time, p_end time,
                                                      p_in time, p_out time) returns tsrange
language sql immutable set search_path = '' as $$
  with b as (
    select p_date + p_start - interval '2 hours' as lo,
           public.ss_end_ts(p_date, p_start, p_end) + interval '4 hours' as hi
  ), i as (
    select coalesce(
             (select c.t from (values (p_date - 1 + p_in), (p_date + p_in), (p_date + 1 + p_in)) as c(t), b
              where c.t >= b.lo and c.t < b.hi order by c.t limit 1),
             case when p_end <= p_start and p_in < p_start then p_date + 1 + p_in else p_date + p_in end) as t
  )
  select tsrange(i.t, i.t::date + p_out + case when p_out <= p_in then interval '1 day' else interval '0' end, '[)')
  from i
$$;


