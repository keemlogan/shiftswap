-- UC-11 / FR-18 / BR-12: a REQUESTED or ACCEPTED request whose deadline or shift start has passed becomes EXPIRED;
-- its pending targets are closed silently; requester and owner receive REQUEST_EXPIRED. Returns the number expired.
create or replace function public.expire_overdue_requests() returns int
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_owner int := public.ss_owner_id();
  v_ids int[];
  v_id int;
  v_params jsonb;
begin
  with expired as (
    update public.sub_request r set status = 'EXPIRED', decided_at = v_now
    from public.shift s
    where s.id = r.shift_id and r.status in ('REQUESTED', 'ACCEPTED')
      and (r.deadline <= v_now or s.work_date + s.start_time <= v_now)
    returning r.id
  )
  select coalesce(array_agg(e.id order by e.id), '{}') into v_ids from expired e;
  foreach v_id in array v_ids loop
    update public.sub_request_target set response = 'CLOSED', responded_at = v_now
    where sub_request_id = v_id and response = 'PENDING';
    v_params := public.ss_request_params(v_id);
    perform public.ss_notify((v_params->>'requester_id')::int, v_id, 'REQUEST_EXPIRED', v_params);
    perform public.ss_notify(v_owner, v_id, 'REQUEST_EXPIRED', v_params);
  end loop;
  return coalesce(array_length(v_ids, 1), 0);
end $$;

-- A3: the System Clock's duties, run whenever a screen is loaded (§9.4): expiry (UC-11), then the payroll drafts of
-- every missing past month (UC-14). Returns {expired, drafted_months}.
create or replace function public.run_system_clock() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_expired int;
begin
  -- Two screens loaded at the same moment run the System Clock one after the other (the second finds nothing left to
  -- do), so two drafts of the same month can never collide on unique (worker_id, year_month).
  perform pg_catalog.pg_advisory_xact_lock(7140812);
  v_expired := public.expire_overdue_requests();
  return jsonb_build_object('expired', v_expired, 'drafted_months', public.ss_prepare_drafts());
end $$;

-- ---- UC-01 Register worker and fixed schedule --------------------------------------------------------------------------

-- FR-01: insert a worker (p_id null) or update one; returns the id.
create or replace function public.save_worker(p_id int, p_name text, p_phone text, p_hourly_wage int,
  p_contract_start date, p_contract_end date, p_probation_end date, p_simple_labor boolean, p_active boolean)
returns int
language plpgsql security definer set search_path = '' as $$
declare
  v_name text := btrim(p_name);
  v_phone text := nullif(btrim(p_phone), '');
  v_id int;
begin
  if v_name is null or char_length(v_name) not between 1 and 60 then
    raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('field', 'name')::text,
      hint = 'Enter the name with 1 to 60 characters.';
  end if;
  if char_length(v_phone) > 30 then
    raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('field', 'phone')::text,
      hint = 'The phone number can have at most 30 characters.';
  end if;
  if p_hourly_wage is null or p_hourly_wage <= 0 then
    raise exception using message = 'WORKER_INVALID',
      detail = jsonb_build_object('field', 'hourly_wage', 'value', p_hourly_wage)::text,
      hint = 'Enter the hourly wage as a whole number of won, for example 10320.';
  end if;
  if p_contract_start is null then
    raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('field', 'contract_start')::text,
      hint = 'Enter the contract start date.';
  end if;
  if p_contract_end < p_contract_start then
    raise exception using message = 'WORKER_INVALID',
      detail = jsonb_build_object('field', 'contract_end', 'contract_start', p_contract_start,
                                  'contract_end', p_contract_end)::text,
      hint = 'The contract end date is before the start date.';
  end if;
  if p_probation_end < p_contract_start then
    raise exception using message = 'WORKER_INVALID',
      detail = jsonb_build_object('field', 'probation_end', 'contract_start', p_contract_start,
                                  'probation_end', p_probation_end)::text,
      hint = 'The probation end date is before the contract start date.';
  end if;
  if p_id is null then
    insert into public.worker (workplace_id, role, name, phone, hourly_wage, contract_start, contract_end,
                               probation_end, simple_labor, active)
    values ((select wp.id from public.workplace wp order by wp.id limit 1), 'WORKER', v_name, v_phone,
            p_hourly_wage, p_contract_start, p_contract_end, p_probation_end, coalesce(p_simple_labor, false),
            coalesce(p_active, true))
    returning id into v_id;
  else
    update public.worker set name = v_name, phone = v_phone, hourly_wage = p_hourly_wage,
      contract_start = p_contract_start, contract_end = p_contract_end, probation_end = p_probation_end,
      simple_labor = coalesce(p_simple_labor, false), active = coalesce(p_active, true)
    where id = p_id and role = 'WORKER'
    returning id into v_id;
    if v_id is null then
      raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('field', 'id', 'id', p_id)::text,
        hint = 'This worker does not exist. Reload the page.';
    end if;
  end if;
  return v_id;
end $$;

-- FR-02: replace the worker's fixed weekly slots with p_slots = [{weekday, start_time, end_time}]. Slots must not
-- overlap on the weekly time line (across midnight and from Sunday into Monday). Unchanged slots keep their row;
-- a deleted slot's shifts are kept. Returns {worker_id, slots, contract_hours}.
create or replace function public.save_fixed_schedule(p_worker_id int, p_slots jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_slots jsonb := '[]'::jsonb;
  v_slot jsonb;
  v_index int := 0;
  v_day int;
  v_start time;
  v_end time;
  v_clash record;
begin
  if not exists (select 1 from public.worker w where w.id = p_worker_id and w.role = 'WORKER') then
    raise exception using message = 'WORKER_INVALID', detail = jsonb_build_object('worker_id', p_worker_id)::text,
      hint = 'Choose a registered worker.';
  end if;
  if p_slots is null or jsonb_typeof(p_slots) <> 'array' then
    raise exception using message = 'TIME_INVALID', detail = jsonb_build_object('field', 'slots')::text,
      hint = 'Send the fixed shifts as a list of {weekday, start_time, end_time}.';
  end if;
  for v_slot in select e from jsonb_array_elements(p_slots) as e loop
    v_index := v_index + 1;
    v_day := case when (v_slot->>'weekday') ~ '^[1-7]$' then (v_slot->>'weekday')::int end;
    v_start := public.ss_parse_time(v_slot->>'start_time');
    v_end := public.ss_parse_time(v_slot->>'end_time');
    if v_day is null or not public.ss_valid_span(v_start, v_end) then
      raise exception using message = 'TIME_INVALID', detail = jsonb_build_object('index', v_index, 'slot', v_slot)::text,
        hint = 'Each fixed shift needs a weekday from 1 (Monday) to 7 (Sunday) and times HH:MM, and lasts 30 minutes to 16 hours.';
    end if;
    v_slots := v_slots || jsonb_build_array(jsonb_build_object('n', v_index, 'weekday', v_day,
                                                               'start_time', v_start, 'end_time', v_end));
  end loop;
  select a.e as a, b.e as b into v_clash
  from jsonb_array_elements(v_slots) as a(e)
  join jsonb_array_elements(v_slots) as b(e) on (a.e->>'n')::int < (b.e->>'n')::int
  where public.ss_slots_overlap((a.e->>'weekday')::int, (a.e->>'start_time')::time, (a.e->>'end_time')::time,
                                (b.e->>'weekday')::int, (b.e->>'start_time')::time, (b.e->>'end_time')::time)
  order by (a.e->>'n')::int, (b.e->>'n')::int
  limit 1;
  if found then
    raise exception using message = 'OVERLAP',
      detail = jsonb_build_object('worker_id', p_worker_id, 'a', v_clash.a - 'n', 'b', v_clash.b - 'n')::text,
      hint = 'Two fixed shifts overlap on the weekly time line (an end not later than the start is on the next day). Change one of them.';
  end if;
  delete from public.fixed_schedule f
  where f.worker_id = p_worker_id
    and not exists (select 1 from jsonb_array_elements(v_slots) as e
                    where (e->>'weekday')::int = f.weekday and (e->>'start_time')::time = f.start_time
                      and (e->>'end_time')::time = f.end_time);
  insert into public.fixed_schedule (worker_id, weekday, start_time, end_time)
  select p_worker_id, (e->>'weekday')::int, (e->>'start_time')::time, (e->>'end_time')::time
  from jsonb_array_elements(v_slots) as e
  where not exists (select 1 from public.fixed_schedule f
                    where f.worker_id = p_worker_id and f.weekday = (e->>'weekday')::int
                      and f.start_time = (e->>'start_time')::time and f.end_time = (e->>'end_time')::time)
  order by (e->>'weekday')::int, (e->>'start_time')::time;
  return jsonb_build_object(
    'worker_id', p_worker_id,
    'slots', (select coalesce(jsonb_agg(jsonb_build_object('id', f.id, 'weekday', f.weekday,
                'start_time', public.ss_hm(f.start_time), 'end_time', public.ss_hm(f.end_time),
                'hours', round(public.ss_minutes(f.start_time, f.end_time) / 60.0, 2))
                order by f.weekday, f.start_time), '[]'::jsonb)
              from public.fixed_schedule f where f.worker_id = p_worker_id),
    'contract_hours', round(public.ss_contract_minutes(p_worker_id) / 60.0, 2));
end $$;

-- ---- UC-03 Manage weekly schedule ----------------------------------------------------------------------------------

-- FR-04: create the shifts of the week (Monday–Sunday) from the fixed slots of active workers, only on dates within
-- each worker's contract period; a slot is skipped when it already produced a shift that week or when the worker
-- already has an overlapping shift. Returns the number of shifts created.
create or replace function public.generate_week(p_week_start date) returns int
language plpgsql security definer set search_path = '' as $$
declare
  v_week date;
  v_count int := 0;
  v_slot record;
begin
  if p_week_start is null then
    raise exception using message = 'TIME_INVALID', detail = jsonb_build_object('field', 'week_start')::text,
      hint = 'Choose the week to generate.';
  end if;
  v_week := public.ss_week_start(p_week_start);
  for v_slot in
    select f.id, f.worker_id, f.start_time, f.end_time, v_week + f.weekday - 1 as work_date
    from public.fixed_schedule f join public.worker w on w.id = f.worker_id
    where w.role = 'WORKER' and w.active
      and (w.contract_start is null or v_week + f.weekday - 1 >= w.contract_start)
      and (w.contract_end is null or v_week + f.weekday - 1 <= w.contract_end)
    order by v_week + f.weekday - 1, f.start_time, f.worker_id, f.id
  loop
    continue when exists (select 1 from public.shift s where s.fixed_schedule_id = v_slot.id
                          and s.work_date between v_week and v_week + 6);
    continue when public.ss_overlapping_shift(v_slot.worker_id, v_slot.work_date, v_slot.start_time,
                                              v_slot.end_time, null) is not null;
    insert into public.shift (work_date, start_time, end_time, worker_id, fixed_schedule_id)
    values (v_slot.work_date, v_slot.start_time, v_slot.end_time, v_slot.worker_id, v_slot.id);
    v_count := v_count + 1;
  end loop;
  if v_count > 0 then
    perform public.ss_recompute_week(v_week);
  end if;
  return v_count;
end $$;

-- FR-05: add a single shift; returns its id.
create or replace function public.add_shift(p_work_date date, p_start time, p_end time, p_worker_id int) returns int
language plpgsql security definer set search_path = '' as $$
declare
  v_id int;
begin
  perform public.ss_check_shift(p_work_date, p_start, p_end, p_worker_id, null);
  insert into public.shift (work_date, start_time, end_time, worker_id)
  values (p_work_date, p_start, p_end, p_worker_id)
  returning id into v_id;
  perform public.ss_recompute_week(p_work_date, array[p_worker_id]);
  return v_id;
end $$;

-- FR-05: move a single shift (date, times, worker). A shift with an open request cannot be changed (SHIFT_LOCKED).
create or replace function public.update_shift(p_shift_id int, p_work_date date, p_start time, p_end time,
                                               p_worker_id int) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_shift public.shift;
  v_open int;
begin
  select * into v_shift from public.shift where id = p_shift_id for update;
  if not found then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
  select r.id into v_open from public.sub_request r
  where r.shift_id = v_shift.id and r.status in ('REQUESTED', 'ACCEPTED');
  if v_open is not null then
    raise exception using message = 'SHIFT_LOCKED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'request_id', v_open)::text,
      hint = 'This shift has an open substitute request. Wait until it is decided or cancelled before changing it.';
  end if;
  perform public.ss_check_shift(p_work_date, p_start, p_end, p_worker_id, v_shift.id);
  update public.shift set work_date = p_work_date, start_time = p_start, end_time = p_end, worker_id = p_worker_id
  where id = v_shift.id;
  perform public.ss_recompute_week(v_shift.work_date,
    array_remove(array[v_shift.worker_id, v_shift.original_worker_id, p_worker_id], null));
  if public.ss_week_start(p_work_date) <> public.ss_week_start(v_shift.work_date) then
    perform public.ss_recompute_week(p_work_date,
      array_remove(array[v_shift.worker_id, v_shift.original_worker_id, p_worker_id], null));
  end if;
end $$;

-- FR-05: delete a single shift; one with a substitute request or an attendance record is kept (SHIFT_HAS_HISTORY).
create or replace function public.delete_shift(p_shift_id int) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_shift public.shift;
begin
  select * into v_shift from public.shift where id = p_shift_id for update;
  if not found then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
  if exists (select 1 from public.sub_request r where r.shift_id = v_shift.id)
     or exists (select 1 from public.attendance a where a.shift_id = v_shift.id) then
    raise exception using message = 'SHIFT_HAS_HISTORY', detail = jsonb_build_object('shift_id', v_shift.id)::text,
      hint = 'This shift has a substitute request or an attendance record, so it cannot be deleted. Move it instead.';
  end if;
  delete from public.shift where id = v_shift.id;
  perform public.ss_recompute_week(v_shift.work_date,
    array_remove(array[v_shift.worker_id, v_shift.original_worker_id], null));
end $$;

-- FR-25 / FR-13: the owner marks a started SCHEDULED shift ABSENT, with or without an attendance record (a no-show
-- has none); the week is recomputed.
create or replace function public.mark_absent(p_shift_id int) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := public.app_now();
  v_shift public.shift;
begin
  select * into v_shift from public.shift where id = p_shift_id for update;
  if not found then
    raise exception using message = 'SHIFT_NOT_FOUND', detail = jsonb_build_object('shift_id', p_shift_id)::text,
      hint = 'This shift does not exist. Reload the page.';
  end if;
  if v_shift.status <> 'SCHEDULED' then
    raise exception using message = 'ATTENDANCE_CLOSED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'status', v_shift.status)::text,
      hint = format('This shift is already %s, so its status cannot change again.', lower(v_shift.status));
  end if;
  if v_shift.work_date + v_shift.start_time > v_now then
    raise exception using message = 'SHIFT_NOT_STARTED',
      detail = jsonb_build_object('shift_id', v_shift.id, 'start_at', v_shift.work_date + v_shift.start_time)::text,
      hint = 'This shift has not started yet, so it cannot be marked absent.';
  end if;
  update public.shift set status = 'ABSENT' where id = v_shift.id and status = 'SCHEDULED';
  update public.attendance set confirmed = true where shift_id = v_shift.id;
  perform public.ss_recompute_week(v_shift.work_date,
    array_remove(array[v_shift.worker_id, v_shift.original_worker_id], null));
end $$;

