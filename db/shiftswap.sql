do $$
declare
  v_roles text;
  v_table text;
  v_sequence text;
  v_function record;
begin
  select string_agg(quote_ident(r.rolname), ', ' order by r.rolname) into v_roles
  from pg_catalog.pg_roles r where r.rolname in ('anon', 'authenticated');
  if v_roles is null then
    return;
  end if;
  foreach v_table in array array['workplace', 'worker', 'fixed_schedule', 'shift', 'sub_request',
                                 'sub_request_target', 'attendance', 'weekly_summary', 'payroll', 'minimum_wage',
                                 'notification'] loop
    execute format('drop policy if exists %I on public.%I', 'read ' || v_table, v_table);
    execute format('create policy %I on public.%I for select to %s using (true)', 'read ' || v_table, v_table, v_roles);
    execute format('revoke all on table public.%I from %s', v_table, v_roles);
    execute format('grant select on table public.%I to %s', v_table, v_roles);
    if exists (select 1 from pg_catalog.pg_attribute a
               where a.attrelid = ('public.' || v_table)::regclass and a.attname = 'id' and a.attidentity <> '') then
      v_sequence := pg_catalog.pg_get_serial_sequence('public.' || v_table, 'id');
      execute format('revoke all on sequence %s from %s', v_sequence, v_roles);
    end if;
  end loop;
  for v_function in
    select p.oid::regprocedure as signature from pg_catalog.pg_proc p
    where p.pronamespace = 'public'::regnamespace
      and p.proname in ('app_now', 'run_system_clock', 'expire_overdue_requests', 'save_worker',
